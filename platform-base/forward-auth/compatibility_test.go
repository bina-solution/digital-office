// The two families are told apart by NAME, and both are accepted. Anything else is refused at load,
// loudly — an unparseable hash is a login page that refuses the owner, which reads as a wrong password.
func TestBothHashFamiliesAreReadAndNothingElseIs(t *testing.T) {
	native, err := hashPassword(testPassword)
	if err != nil {
		t.Fatal(err)
	}
	for encoded, want := range map[string]string{
		native: hashScheme,
		djangoHash(t, testPassword, djangoSalt(t), 1000): legacyScheme,
	} {
		if got, err := hashFamily(encoded); err != nil || got != want {
			t.Errorf("hashFamily(%q…) = %q, %v; want %q", encoded[:12], got, err, want)
		}
	}
	for _, bad := range []string{
		"plaintext", "", "pbkdf2-sha256$1000$only-three-fields",
		"pbkdf2_sha512$1000$aaaa$bbbb", // a family authentik does not use here
		"pbkdf2_sha256$0$aaaaaaaaaaaaaaaaaaaaaa$" + strings.Repeat("A", 44),
		"pbkdf2_sha256$nope$aaaaaaaaaaaaaaaaaaaaaa$" + strings.Repeat("A", 44),
		"pbkdf2_sha256$1000$$" + strings.Repeat("A", 44),
	} {
		if _, err := hashFamily(bad); err == nil {
			t.Errorf("an unparseable hash was accepted: %q", bad)
		}
	}
}

