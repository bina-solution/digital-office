const djangoAlphabet = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"

// djangoSalt mints a salt the way Django's `BasePasswordHasher.salt()` does: 22 characters (128 bits,
// `salt_entropy`) drawn from `RANDOM_STRING_CHARS` — ALPHANUMERIC, not base64. That distinction is
// the whole reason `parseHash` handles the two families differently.
func djangoSalt(t *testing.T) string {
	t.Helper()
	out := make([]byte, 22)
	for i := range out {
		n, err := rand.Int(rand.Reader, big.NewInt(int64(len(djangoAlphabet))))
		if err != nil {
			t.Fatal(err)
		}
		out[i] = djangoAlphabet[n.Int64()]
	}
	return string(out)
}

// djangoHash builds an entry byte-for-byte the way Django's `PBKDF2PasswordHasher.encode()` does:
// the salt is fed to PBKDF2 as its ASCII characters, and the digest is STANDARD base64 WITH padding.
func djangoHash(t *testing.T, password, salt string, iter int) string {
	t.Helper()
	sum := pbkdf2SHA256([]byte(password), []byte(salt), iter, keyLen)
	return fmt.Sprintf("%s$%d$%s$%s", legacyScheme, iter, salt, base64.StdEncoding.EncodeToString(sum))
}

