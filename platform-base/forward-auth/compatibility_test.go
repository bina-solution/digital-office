// The strongest form of the claim: the row below was written by DJANGO, not by this repository, and
// this service verifies it as it stands. If this test ever fails, a migrated office cannot sign in.
func TestADjangoWrittenRowVerifiesHereItself(t *testing.T) {
	ok, err := checkPassword(djangoRowFromTheRealHasher, djangoRowPassphrase)
	if err != nil {
		t.Fatalf("a row Django wrote did not even parse: %v", err)
	}
	if !ok {
		t.Fatal("a row Django wrote did NOT verify — a migrated office would need a password reset")
	}
	if ok, _ := checkPassword(djangoRowFromTheRealHasher, djangoRowPassphrase+"x"); ok {
		t.Fatal("a wrong password was accepted against Django's own row")
	}
	// The same row through the store, which is what a migrated users file actually hits.
	st := &userStore{byName: map[string]*user{}}
	st.byName["akadmin"] = &user{Name: "akadmin", UID: djangoUID, hash: djangoRowFromTheRealHasher, legacy: true}
	if _, ok := st.verify("akadmin", djangoRowPassphrase); !ok {
		t.Fatal("the store refused the correct password on Django's own row")
	}
}

// …and the other direction, which is the one that keeps the helper honest: a row built by THIS
// repository's `djangoHash()` is accepted by Django's own verifier. Run against the live image on
// 2026-10-09 it answered `DJANGO_VERIFIED_GO_ROW= True` / `DJANGO_REFUSED_WRONG= True`; the command
// is in §"Migration" of the design note, because it needs the container and is not part of this
// suite. What is asserted HERE is what can be asserted without one: that the fixture generator
// produces Django's shape, field for field, including the salted-and-padded digest.
func TestBDjangoHashHelperProducesDjangosOwnShape(t *testing.T) {
	// 1000 iterations here on purpose: SHAPE does not depend on the work factor, and the real
	// 720_000 is exercised at its real cost by the three tests above and below this one.
	for i := 0; i < 3; i++ {
		salt := djangoSalt(t)
		if len(salt) != 22 {
			t.Fatalf("salt is %d characters, Django's is 22 (ceil(128 bits / log2(62)))", len(salt))
		}
		if strings.ContainsAny(salt, "+/=$") {
			t.Fatalf("salt %q is not drawn from Django's own [A-Za-z0-9] alphabet", salt)
		}
		h := djangoHash(t, testPassword, salt, 1000)
		parts := strings.Split(h, "$")
		if got := fmt.Sprint(len(parts), "/", len(parts[0]), "/", len(parts[2]), "/", len(parts[3])); got != "4/13/22/44" {
			t.Fatalf("field shape = %s, Django's live row is 4/13/22/44", got)
		}
		if parts[0] != "pbkdf2_sha256" {
			t.Fatalf("scheme = %s", parts[0])
		}
		if !strings.HasSuffix(parts[3], "=") {
			t.Fatal("the digest is not padded — Django base64-encodes with padding")
		}
	}
	// The work factor Django 5.0 actually writes, read off the row Django itself wrote above.
	if iter := strings.Split(djangoRowFromTheRealHasher, "$")[1]; iter != "720000" {
		t.Fatalf("Django wrote %s iterations; the live office's own rows carry 720000", iter)
	}
}

// The claim: an existing `pbkdf2_sha256$720000$<salt>$<hash>` row authenticates against this
// service with NO password reset. The test also pins the SHAPE — 13/6/22/44 characters and a padded
// digest — so a future refactor that "simplifies" the parser cannot quietly stop matching the rows
// in the database while still passing on a fixture of its own making.
func TestAuthentikPasswordHashVerifies(t *testing.T) {
	salt := djangoSalt(t)
	h := djangoHash(t, testPassword, salt, djangoIterations)

	parts := strings.Split(h, "$")
	if len(parts) != 4 {
		t.Fatalf("fixture is not 4 fields: %q", h)
	}
	for _, want := range []struct {
		name string
		got  int
		n    int
	}{
		{"scheme", len(parts[0]), 13}, {"iterations", len(parts[1]), 6},
		{"salt", len(parts[2]), 22}, {"digest", len(parts[3]), 44},
	} {
		if want.got != want.n {
			t.Errorf("fixture %s is %d characters, the live row is %d", want.name, want.got, want.n)
		}
	}
	if !strings.HasSuffix(parts[3], "=") {
		t.Error("the digest is not padded — Django base64-encodes with padding, and a 32-byte digest ends '='")
	}
	if strings.ContainsAny(parts[2], "+/=") {
		t.Errorf("the salt %q uses base64 punctuation; Django's alphabet is [A-Za-z0-9]", parts[2])
	}

	if ok, err := checkPassword(h, testPassword); err != nil || !ok {
		t.Fatalf("an authentik hash did not verify: ok=%v err=%v", ok, err)
	}
	// The store path too, not just the function: this is what a migrated users file actually hits.
	st := &userStore{byName: map[string]*user{}}
	st.byName["akadmin"] = &user{Name: "akadmin", UID: djangoUID, hash: h, legacy: true}
	if _, ok := st.verify("akadmin", testPassword); !ok {
		t.Fatal("the store refused a correct password on a migrated line")
	}
}

// A wrong password is refused — and, the half that matters more, a password that differs only in a
// way a sloppy comparison would forgive is refused too. Django's own verify re-encodes the WHOLE
// entry, so padding, spelling and salt encoding are all part of the comparison; this pins that.
func TestWrongPasswordIsRefusedAgainstAuthentikHash(t *testing.T) {
	salt := djangoSalt(t)
	h := djangoHash(t, testPassword, salt, 1000)

	for name, wrong := range map[string]string{
		"a different password":  "not the password",
		"a suffix":              testPassword + "x",
		"a prefix":              "x" + testPassword,
		"case":                  strings.ToUpper(testPassword),
		"empty":                 "",
		"the hash itself":       h,
		"just the digest":       strings.Split(h, "$")[3],
		"just the salt":         salt,
		"the salt as base64":    base64.StdEncoding.EncodeToString([]byte(salt)),
		"a trailing space":      testPassword + " ",
		"a leading space":       " " + testPassword,
		"the password reversed": reverse(testPassword),
	} {
		if ok, err := checkPassword(h, wrong); err != nil || ok {
			t.Errorf("%s was ACCEPTED against an authentik hash (ok=%v err=%v)", name, ok, err)
		}
	}

	// The same refusal, at the live row's OWN cost (720000), so the parameters that are actually in
	// the database are on the path that has to say no — not only on the one that says yes.
	live := djangoHash(t, testPassword, salt, djangoIterations)
	if ok, err := checkPassword(live, testPassword); err != nil || !ok {
		t.Fatalf("the live parameter set did not verify: ok=%v err=%v", ok, err)
	}
	if ok, _ := checkPassword(live, testPassword+" "); ok {
		t.Error("the live parameter set accepted a wrong password")
	}

	// A digest at the wrong length must not be silently zero-padded into a match.
	short := fmt.Sprintf("%s$%d$%s$%s", legacyScheme, 1000, salt,
		base64.StdEncoding.EncodeToString(make([]byte, 16)))
	if ok, err := checkPassword(short, testPassword); err != nil || ok {
		t.Errorf("a truncated digest verified (ok=%v err=%v)", ok, err)
	}

	// …and the iteration count is read from the row, so a row written at another cost still works.
	for _, iter := range []int{1, 1000, 210_000} {
		other := djangoHash(t, testPassword, salt, iter)
		if ok, err := checkPassword(other, testPassword); err != nil || !ok {
			t.Errorf("a row at %d iterations did not verify: ok=%v err=%v", iter, ok, err)
		}
	}
}

func reverse(s string) string {
	r := []rune(s)
	for i, j := 0, len(r)-1; i < j; i, j = i+1, j-1 {
		r[i], r[j] = r[j], r[i]
	}
	return string(r)
}

