// With no snapshot configured the legacy reader does not exist, and an authentik cookie is simply
// an unknown cookie. That is the steady state after the migration, and it must not be a crash.
func TestLegacyAcceptanceIsOffWhenNotConfigured(t *testing.T) {
	s := testServer(t)
	c := &http.Cookie{Name: legacyCookieName, Value: legacyCookie(t, djangoSecret, liveClaims(djangoUID))}
	w := httptest.NewRecorder()
	s.forwardAuth(w, fwdReq("GET", "console.localhost", "/", c))
	if w.Code != http.StatusFound {
		t.Fatalf("status = %d, want 302 when no snapshot is configured", w.Code)
	}

	// Configuration is both-or-neither, and a snapshot that cannot be read is fatal rather than a
	// silent "everybody is signed out".
	base := func() {
		t.Setenv("FORWARD_AUTH_EXTERNAL_URL", "http://auth.localhost")
		t.Setenv("FORWARD_AUTH_ALLOWED_HOSTS", ".localhost")
		t.Setenv("FORWARD_AUTH_SECRET", testSecret)
	}
	base()
	t.Setenv("FORWARD_AUTH_LEGACY_SECRET", djangoSecret)
	os.Unsetenv("FORWARD_AUTH_LEGACY_SESSIONS")
	if _, err := configFromEnv(); err == nil {
		t.Error("a legacy secret with no snapshot was accepted")
	}
	t.Setenv("FORWARD_AUTH_LEGACY_SECRET", "")
	t.Setenv("FORWARD_AUTH_LEGACY_SESSIONS", "/nonexistent/sessions")
	if _, err := configFromEnv(); err == nil {
		t.Error("a snapshot with no secret was accepted")
	}

	// Both, and readable: accepted, and the derived key is authentik's own derivation.
	dir := t.TempDir()
	path := dir + "/legacy-sessions"
	exp := time.Now().Add(48 * time.Hour).Unix()
	if err := os.WriteFile(path, []byte("# sid username expiry\n"+djangoSID+" akadmin "+fmt.Sprint(exp)+"\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Setenv("FORWARD_AUTH_LEGACY_SECRET", djangoSecret)
	t.Setenv("FORWARD_AUTH_LEGACY_SESSIONS", path)
	cfg, err := configFromEnv()
	if err != nil {
		t.Fatalf("a complete legacy configuration was refused: %v", err)
	}
	if cfg.legacySessions == nil || len(cfg.legacySessions.bySID) != 1 {
		t.Fatalf("the snapshot did not load: %+v", cfg.legacySessions)
	}
	want := sha512.Sum512([]byte(djangoSecret))
	if got := string(legacySigningKey(cfg.legacySecretKey)); got != hex.EncodeToString(want[:]) {
		t.Error("the derived signing key is not sha512(secret).hexdigest(), which is authentik's own SIGNING_HASH")
	}
}

// A malformed snapshot line is fatal for the same reason a malformed users line is: a snapshot that
// quietly lost the line you are standing in front of looks exactly like "your session expired".
func TestLegacySnapshotParsing(t *testing.T) {
	dir := t.TempDir()
	path := dir + "/s"
	write := func(s string) {
		if err := os.WriteFile(path, []byte(s), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("# comment\n\n" + djangoSID + " akadmin 1893456000\n")
	ls, err := loadLegacySessions(path)
	if err != nil {
		t.Fatalf("a well-formed snapshot was refused: %v", err)
	}
	if e := ls.bySID[djangoSID]; e.username != "akadmin" || !e.exp.Equal(time.Unix(1893456000, 0)) {
		t.Fatalf("entry = %+v", e)
	}
	for _, bad := range []string{
		djangoSID + " akadmin\n",                                // two fields
		djangoSID + " akadmin not-a-time\n",                     // expiry is not a number
		djangoSID + " akadmin 1\n" + djangoSID + " akadmin 2\n", // duplicate sid
		"# only a comment\n",                                    // nothing to accept
	} {
		write(bad)
		if _, err := loadLegacySessions(path); err == nil {
			t.Errorf("a malformed snapshot was accepted: %q", bad)
		}
	}
}

// ── 3. the header contract: the five names, exactly ──────────────────────────────────────────────

// The claim: five names, spelled exactly as the ten runtime readers spell them, with groups joined
// by `|`. The middleware's `authResponseHeaders` is the consumer that makes the spelling binding —
// traefik copies a header by NAME, so one character of drift silently sends every app an empty
// identity. This asserts the SET, so adding a sixth (or dropping one) fails here rather than in
// production.
func TestIdentityHeadersAreExactlyTheFiveNames(t *testing.T) {
	u := &user{
		Name: "akadmin", Email: "ci@example.com", Display: "authentik Default Admin",
		UID: djangoUID, Groups: []string{"admins", "incoming-docs-admin"},
	}
	got := identityHeaders(u)

	want := []string{
		"X-authentik-username", "X-authentik-email", "X-authentik-name",
		"X-authentik-uid", "X-authentik-groups",
	}
	if len(got) != len(want) {
		t.Fatalf("identityHeaders returns %d headers, want exactly %d: %v", len(got), len(want), got)
	}
	for _, name := range want {
		if _, ok := got[name]; !ok {
			t.Errorf("the header set is missing %s", name)
		}
	}

	// The values, as the estate parses them — `|` is what console/app.py:83 and indox split on.
	for name, v := range map[string]string{
		"X-authentik-username": "akadmin",
		"X-authentik-email":    "ci@example.com",
		"X-authentik-name":     "authentik Default Admin",
		"X-authentik-uid":      djangoUID,
		"X-authentik-groups":   "admins|incoming-docs-admin",
	} {
		if got[name] != v {
			t.Errorf("%s = %q, want %q", name, got[name], v)
		}
	}

	// The names traefik's middleware lists and THIS service deliberately does not produce. Emitting
	// them would be a false claim of a signed token (design note §1.6: nothing reads them).
	for _, absent := range []string{
		"X-authentik-jwt", "X-authentik-meta-jwks", "X-authentik-meta-outpost",
		"X-authentik-meta-provider", "X-authentik-meta-app", "X-authentik-meta-version",
	} {
		if _, ok := got[absent]; ok {
			t.Errorf("%s is produced but nothing in the estate reads it", absent)
		}
	}
}

// The same five names arrive over the wire on a real response, with a legacy cookie as the session,
// and an anonymous caller gets none of them.
func TestForwardAuthEmitsTheFiveOverTheWire(t *testing.T) {
	s, _ := migratedServer(t)
	c := &http.Cookie{Name: legacyCookieName, Value: legacyCookie(t, djangoSecret, liveClaims(djangoUID))}

	w := httptest.NewRecorder()
	s.forwardAuth(w, fwdReq("GET", "console.localhost", "/apps", c))
	if w.Code != http.StatusOK {
		t.Fatalf("status = %d", w.Code)
	}
	authn := []string{}
	for name := range w.Header() {
		if strings.HasPrefix(strings.ToLower(name), "x-authentik-") {
			authn = append(authn, http.CanonicalHeaderKey(name))
		}
	}
	if len(authn) != 5 {
		t.Fatalf("the response carries %d X-authentik-* headers (%v), want 5", len(authn), authn)
	}

	// Anonymous: not one of them, or traefik would copy an empty identity onto the app.
	w2 := httptest.NewRecorder()
	s.forwardAuth(w2, fwdReq("GET", "console.localhost", "/apps", nil))
	if w2.Code != http.StatusFound {
		t.Fatalf("anonymous status = %d, want 302", w2.Code)
	}
	for name := range w2.Header() {
		if strings.HasPrefix(strings.ToLower(name), "x-authentik-") {
			t.Errorf("an anonymous response carries %s", name)
		}
	}
}

// A migrated office signs in again with the SAME password — the fallback the design note documents
// for the case where the owner will not hand over `AUTHENTIK_SECRET_KEY`. It is proven here because
// "no reconnection" rests on it: nothing is reset, nothing is re-authorized, the form just works.
func TestMigratedUserSignsInWithTheSamePassword(t *testing.T) {
	s, _ := migratedServer(t)

	form := url.Values{"user": {"akadmin"}, "password": {testPassword}, "rd": {"http://console.localhost/apps"}}
	r := httptest.NewRequest("POST", "/login", strings.NewReader(form.Encode()))
	r.Header.Set("Content-Type", "application/x-www-form-urlencoded")
	w := httptest.NewRecorder()
	s.login(w, r)

	if w.Code != http.StatusSeeOther {
		t.Fatalf("status = %d, want 303 — the owner's existing password was not accepted", w.Code)
	}
	res := w.Result()
	cookies := res.Cookies()
	if len(cookies) != 1 || cookies[0].Name != cookieName {
		t.Fatalf("cookies = %v, want exactly one %s", cookies, cookieName)
	}

	// …and the cookie this service mints is the one it accepts, so the session is now ours.
	w2 := httptest.NewRecorder()
	s.forwardAuth(w2, fwdReq("GET", "console.localhost", "/apps", cookies[0]))
	if w2.Code != http.StatusOK {
		t.Fatalf("forward-auth with the new cookie = %d, want 200", w2.Code)
	}
}
