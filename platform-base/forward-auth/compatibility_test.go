// The strongest form of the claim: the token below was minted by PYJWT — the library authentik's
// SessionMiddleware calls — with the key derivation that file uses, and this service accepts it.
func TestAPyJWTWrittenCookieIsAccepted(t *testing.T) {
	s, _ := migratedServer(t)
	c := &http.Cookie{Name: legacyCookieName, Value: pyjwtCookieFromTheRealLibrary}

	w := httptest.NewRecorder()
	s.forwardAuth(w, fwdReq("GET", "console.localhost", "/apps", c))
	if w.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200 — a PyJWT-minted authentik session did not survive the swap", w.Code)
	}
	for name, want := range map[string]string{
		"X-authentik-username": "akadmin",
		"X-authentik-uid":      djangoUID,
		"X-authentik-email":    "ci@example.com",
	} {
		if got := w.Header().Get(name); got != want {
			t.Errorf("%s = %q, want %q", name, got, want)
		}
	}
	// The same token under a different key must fail: that is the whole value of the signature.
	if _, err := verifyLegacyJWT(pyjwtCookieFromTheRealLibrary, legacySigningKey("another-secret")); err == nil {
		t.Fatal("PyJWT's token verified under the wrong key")
	}
	// And without the key at all there is no acceptance — the fallback the design note documents.
	bare := testServer(t)
	w2 := httptest.NewRecorder()
	bare.forwardAuth(w2, fwdReq("GET", "console.localhost", "/", c))
	if w2.Code != http.StatusFound {
		t.Fatalf("with no legacy configuration the status = %d, want 302", w2.Code)
	}
}

// The claim: a browser holding `authentik_session` before the swap is still signed in after it.
func TestLegacyAuthentikCookieIsAccepted(t *testing.T) {
	s, _ := migratedServer(t)
	c := &http.Cookie{Name: legacyCookieName, Value: legacyCookie(t, djangoSecret, liveClaims(djangoUID))}

	w := httptest.NewRecorder()
	s.forwardAuth(w, fwdReq("GET", "console.localhost", "/apps", c))
	if w.Code != http.StatusOK {
		t.Fatalf("status = %d, want 200 — an authentik session did not survive the swap", w.Code)
	}
	if got := w.Header().Get("X-authentik-username"); got != "akadmin" {
		t.Fatalf("X-authentik-username = %q, want akadmin", got)
	}
	// The uid is the one fact an app may have stored: it must be authentik's own, not a new one.
	if got := w.Header().Get("X-authentik-uid"); got != djangoUID {
		t.Errorf("X-authentik-uid = %q, want authentik's own uid %q", got, djangoUID)
	}

	// /whoami answers from the same cookie, so the console's and the agent's view agree with ours.
	w2 := httptest.NewRecorder()
	s.whoami(w2, withCookie(httptest.NewRequest("GET", "/whoami", nil), c))
	if w2.Code != http.StatusOK {
		t.Fatalf("/whoami with a legacy cookie = %d, want 200", w2.Code)
	}
}

func withCookie(r *http.Request, c *http.Cookie) *http.Request { r.AddCookie(c); return r }

// Every way an authentik cookie can be wrong is refused, and all of them look the same from outside.
func TestForgedOrDeadLegacyCookiesAreRefused(t *testing.T) {
	s, ls := migratedServer(t)
	good := legacyCookie(t, djangoSecret, liveClaims(djangoUID))

	// An HS256 token signed with someone else's key — the forgery that matters, because it is a
	// VALID signature and only the key distinguishes it.
	foreign := legacyCookie(t, "a-different-secret-entirely-0123456789", liveClaims(djangoUID))

	// `alg: none` is the classic JWT forgery: an unsigned token claiming to be signed.
	noneHead := base64.RawURLEncoding.EncodeToString([]byte(`{"typ":"JWT","alg":"none"}`))
	noneBody := base64.RawURLEncoding.EncodeToString(mustJSON(t, liveClaims(djangoUID)))
	unsigned := noneHead + "." + noneBody + "."

	anonymous := legacyCookie(t, djangoSecret, map[string]any{
		"sid": djangoSID, "iss": "authentik", "sub": "anonymous",
		"authenticated": false, "acr": "goauthentik.io/core/default",
	})
	otherIssuer := legacyCookie(t, djangoSecret, map[string]any{
		"sid": djangoSID, "iss": "somebody-else", "sub": djangoUID, "authenticated": true,
	})
	unknownSID := legacyCookie(t, djangoSecret, func() map[string]any {
		c := liveClaims(djangoUID)
		c["sid"] = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
		return c
	}())
	// A snapshot line pointing at the wrong person must not be believed either: the JWT's `sub` and
	// the snapshot's username have to agree.
	mismatched := legacyCookie(t, djangoSecret, liveClaims(strings.Repeat("f", 64)))

	for name, value := range map[string]string{
		"tampered signature":      good[:len(good)-4] + "AAAA",
		"signed with another key": foreign,
		"alg none":                unsigned,
		"an anonymous session":    anonymous,
		"another issuer":          otherIssuer,
		"a session not live":      unknownSID,
		"the uid does not match":  mismatched,
		"not a jwt":               "p57wq3i528lzy0xavm3lbnvk6bwn9bfn",
		"empty":                   "",
	} {
		w := httptest.NewRecorder()
		s.forwardAuth(w, fwdReq("GET", "console.localhost", "/", &http.Cookie{Name: legacyCookieName, Value: value}))
		if w.Code != http.StatusFound {
			t.Errorf("%s: status = %d, want 302 (refused)", name, w.Code)
		}
		if v := w.Header().Get("X-authentik-username"); v != "" {
			t.Errorf("%s: served identity %q", name, v)
		}
	}

	// A session authentik itself would have stopped honouring is refused too — the snapshot is what
	// makes the acceptance a LIVE session rather than a signature that never expires.
	ls.bySID[djangoSID] = legacyEntry{username: "akadmin", exp: time.Now().Add(-time.Minute)}
	w := httptest.NewRecorder()
	s.forwardAuth(w, fwdReq("GET", "console.localhost", "/", &http.Cookie{Name: legacyCookieName, Value: good}))
	if w.Code != http.StatusFound {
		t.Errorf("an expired authentik session was accepted: %d", w.Code)
	}
}

