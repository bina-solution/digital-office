// legacyCookie mints an `authentik_session` cookie the way authentik's SessionMiddleware does:
// PyJWT with the default algorithm, keyed by `sha512(SECRET_KEY).hexdigest()`.
func legacyCookie(t *testing.T, secretKey string, claims map[string]any) string {
	t.Helper()
	enc := func(v any) string {
		b, err := json.Marshal(v)
		if err != nil {
			t.Fatal(err)
		}
		return base64.RawURLEncoding.EncodeToString(b)
	}
	// PyJWT's own JSON, compact and in this order: {"typ":"JWT","alg":"HS256"}.
	head := base64.RawURLEncoding.EncodeToString([]byte(`{"typ":"JWT","alg":"HS256"}`))
	body := enc(claims)
	mac := hmac.New(sha256.New, legacySigningKey(secretKey))
	mac.Write([]byte(head + "." + body))
	return head + "." + body + "." + base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
}

