#!/usr/bin/env python3
"""
supabase-keygen — generate the self-hosted Supabase secrets (JWT secret + anon/service-role JWTs +
db/authenticator passwords) and write any that are missing into the root .env (idempotent, never
overwrites an existing key). HS256 JWTs are minted with stdlib only (hmac/hashlib/base64) — no deps.

Usage: python3 scripts/supabase-keygen.py [--print] [--force]
  --force  regenerate even if present (rotates keys — only when you mean it)
Secrets live in .env (gitignored), never in git. Mirrors the project's declarative-secrets pattern.
"""
import os, sys, json, hmac, hashlib, base64, secrets, time

def _repo_root(start):
    # Walk up to the repo root (the dir holding `bbox`). This hook lives at
    # platform-base/supabase/hooks/keygen.py; the old `dirname(dirname(__file__))` resolved to
    # platform-base/supabase/ after the refactor moved it into hooks/, so it wrote the keys into
    # platform-base/supabase/.env — which the supabase compose reads, but the CONSUMER apps
    # (drive/apitools/indox) interpolate from the repo-root .env and so got EMPTY anon/service
    # keys → drive uploads to supabase storage failed with "Invalid Compact JWS". Anchor on the
    # repo root so every service reads one .env, matching this file's docstring.
    d = os.path.dirname(os.path.abspath(start))
    while d != os.path.dirname(d):
        if os.path.exists(os.path.join(d, 'bbox')):
            return d
        d = os.path.dirname(d)
    return os.path.dirname(os.path.dirname(os.path.abspath(start)))


ROOT = _repo_root(__file__)
ENV = os.path.join(ROOT, '.env')
PRINT = '--print' in sys.argv
FORCE = '--force' in sys.argv

# JWTs valid for ~10 years (self-hosted, internal) — matches Supabase's long-lived anon/service keys
EXP = int(time.time()) + 10 * 365 * 24 * 3600
IAT = int(time.time())


def b64url(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).decode().rstrip('=')


def jwt_hs256(payload: dict, secret: str) -> str:
    header = {"alg": "HS256", "typ": "JWT"}
    seg = b64url(json.dumps(header, separators=(',', ':')).encode()) + '.' + \
          b64url(json.dumps(payload, separators=(',', ':')).encode())
    sig = hmac.new(secret.encode(), seg.encode(), hashlib.sha256).digest()
    return seg + '.' + b64url(sig)


def read_env() -> dict:
    d = {}
    if os.path.exists(ENV):
        for ln in open(ENV, encoding='utf-8', errors='replace'):
            if '=' in ln and not ln.lstrip().startswith('#'):
                k, v = ln.split('=', 1)
                d[k.strip()] = v.rstrip('\n')
    return d


def main():
    cur = read_env()
    jwt_secret = cur.get('SUPABASE_JWT_SECRET') if not FORCE else None
    if not jwt_secret:
        jwt_secret = secrets.token_hex(32)  # 64 hex chars

    out = {
        'SUPABASE_POSTGRES_PASSWORD': cur.get('SUPABASE_POSTGRES_PASSWORD') if not FORCE else None,
        'SUPABASE_AUTHENTICATOR_PASSWORD': cur.get('SUPABASE_AUTHENTICATOR_PASSWORD') if not FORCE else None,
        'SUPABASE_JWT_SECRET': jwt_secret,
        'SUPABASE_ANON_KEY': cur.get('SUPABASE_ANON_KEY') if not FORCE else None,
        'SUPABASE_SERVICE_KEY': cur.get('SUPABASE_SERVICE_KEY') if not FORCE else None,
    }
    out['SUPABASE_POSTGRES_PASSWORD'] = out['SUPABASE_POSTGRES_PASSWORD'] or secrets.token_hex(24)
    out['SUPABASE_AUTHENTICATOR_PASSWORD'] = out['SUPABASE_AUTHENTICATOR_PASSWORD'] or secrets.token_hex(24)
    out['SUPABASE_ANON_KEY'] = out['SUPABASE_ANON_KEY'] or jwt_hs256(
        {"role": "anon", "iss": "supabase", "iat": IAT, "exp": EXP}, jwt_secret)
    out['SUPABASE_SERVICE_KEY'] = out['SUPABASE_SERVICE_KEY'] or jwt_hs256(
        {"role": "service_role", "iss": "supabase", "iat": IAT, "exp": EXP}, jwt_secret)

    # append only the missing keys
    existing = read_env()
    to_add = {k: v for k, v in out.items() if FORCE or k not in existing}
    if to_add:
        with open(ENV, 'a', encoding='utf-8') as f:
            f.write('\n# --- Supabase (self-hosted INDOX data/file layer) — generated by scripts/supabase-keygen.py ---\n')
            for k, v in to_add.items():
                f.write(f'{k}={v}\n')
        print(f"wrote {len(to_add)} key(s) to .env: {', '.join(to_add)}")
    else:
        print("all Supabase keys already present in .env (use --force to rotate)")

    if PRINT:
        for k in out:
            print(f"{k}={out[k]}")


if __name__ == '__main__':
    main()
