# -*- coding: utf-8 -*-
"""Generate a full synthetic document corpus mirroring demo-docs/.

Runs inside the apitools container (needs fitz + src.doc_gen). Produces, under an
output root, the same per-type layout as apps/indox/blueprint/demo-docs:

  <root>/<folder>/files/<name>.<ext>     one rendered document each
  <root>/companies.json                  the businesses used (id + name)
  <root>/truth.json                      manifest: file -> model + extraction_truth
  <root>/README.md

Every document is generated from a typed model whose extraction_truth() IS the
ground truth — so truth.json is authoritative, not a re-extraction.

Usage (in container):  python3 scripts/gen_synth_corpus.py /tmp/synth
"""
import json
import os
import sys

sys.path.insert(0, '/app')

from src.doc_models import sample                       # noqa: E402
from src.doc_models.sampler import SUPPLIERS, CUSTOMER  # noqa: E402
from src.doc_gen import render                          # noqa: E402

# folder (demo-docs name) -> (DOC_TYPE, count, file-ext).
# Covers ALL registered document types (src/doc_models DOC_TYPES).
PLAN = {
    'invoice':         ('INVOICE', 24, 'pdf'),
    'invoice_receipt': ('INVOICE_RECEIPT', 12, 'pdf'),
    'order':           ('ORDER', 10, 'pdf'),
    'quote':           ('QUOTE', 8, 'pdf'),
    'shipment':        ('SHIPMENT', 16, 'pdf'),
    'balance_sheet':   ('BALANCE_SHEET', 12, 'pdf'),
    'receipt':         ('RECEIPT', 8, 'pdf'),
}
ABBR = {'invoice': 'inv', 'invoice_receipt': 'ir', 'order': 'ord', 'quote': 'qt',
        'shipment': 'shp', 'balance_sheet': 'bs', 'receipt': 'rcp'}


def main(root):
    manifest = []
    for folder, (typ, count, ext) in PLAN.items():
        fdir = os.path.join(root, folder, 'files')
        os.makedirs(fdir, exist_ok=True)
        for i in range(1, count + 1):
            m = sample(typ, i)
            data = render(m, ext)
            name = '%s-%02d.%s' % (ABBR[folder], i, ext)
            with open(os.path.join(fdir, name), 'wb') as fh:
                fh.write(data)
            manifest.append({
                'folder': folder,
                'file': '%s/files/%s' % (folder, name),
                'doc_type': m.DOC_TYPE,
                'doc_id': m.doc_id or getattr(m, 'account_no', ''),
                'short_doc_id': m.short_doc_id,
                'company_id': m.supplier.company_id,
                'company_name': m.supplier.name,
                'truth': m.extraction_truth(),
            })
        print('  %-14s %2d x %s' % (folder, count, ext))

    companies = ([{'id': cid, 'name': name} for name, cid, _s, _c in SUPPLIERS]
                 + [{'id': CUSTOMER.company_id, 'name': CUSTOMER.name}])
    _w(os.path.join(root, 'companies.json'), companies)
    _w(os.path.join(root, 'truth.json'),
       {'generator': 'apitools doc-gen', 'count': len(manifest), 'documents': manifest})
    with open(os.path.join(root, 'README.md'), 'w', encoding='utf-8') as fh:
        fh.write(
            '# synth-demo-docs\n\n'
            'Fully **synthetic** document corpus, same layout as `demo-docs/`, generated by '
            'the apitools doc-gen API (`src/doc_gen`) from typed data models (`src/doc_models`).\n\n'
            'Each document is realistic Israeli-business-grade (logo, מסמך ממוחשב, מקור, '
            'allocation number, Instruction-36 footer) and **its model is its own ground truth** — '
            'see `truth.json` (`documents[].truth` = the exact extraction contract each doc yields).\n\n'
            'Regenerate: `python3 scripts/gen_synth_corpus.py <out>` inside the apitools container.\n\n'
            '| folder | type | files |\n|---|---|---|\n'
            + ''.join('| %s | %s | %d |\n' % (f, p[0], p[1]) for f, p in PLAN.items()))
    print('total: %d documents  ->  %s' % (len(manifest), root))


def _w(path, obj):
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(obj, fh, ensure_ascii=False, indent=1)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/synth')
