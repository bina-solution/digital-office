"""Private-mail setup checker — "what is still missing before mail from this deployment arrives?"

Receiving mail at your own domain is not one switch. It is a handful of facts that must agree with
each other, spread across DNS, the host's network, and this container. Any one of them wrong and the
symptom is the same useless one: mail vanishes, or lands in spam. Every failure this platform has
actually hit was one of these, and each took hours to find because nothing could answer the question
directly:

  · the DKIM SigningTable matched exact addresses, so the server signed nothing        (silent)
  · the host firewall's DOCKER-USER chain dropped inbound 25 before Postfix saw it     (silent)
  · reverse DNS still answered with the old name, so receivers distrusted the banner   (silent)
  · a key existed on one VPS and nowhere else, because it was generated by hand        (silent)
  · a corrected PTR was live at the provider and on 1.1.1.1 while 8.8.8.8 still served
    the old name from cache, so the checklist went green, then red, then green again   (loud, wrong)

So this module asks each question out loud and reports the answer, and the UI renders it as a
checklist with the exact record to publish. The operator of a company deployment can then finish
their own setup without needing us.

Design rules, learned from the above:

  · Never infer. Every check reports what it OBSERVED next to what was EXPECTED. A check that says
    "probably fine" is how the DKIM bug survived.
  · Distinguish "wrong" from "unknowable". A laptop behind a residential NAT cannot receive public
    mail, and saying so plainly is useful; inventing a public IP for it is not.
  · Compare against what the MTA actually uses — the DKIM public key is read off the very key file
    OpenDKIM signs with, not re-derived. A checker with its own copy of the truth can agree with
    itself while the server disagrees with both.
  · One resolver is one OPINION, not the truth. DNS does not change, it CONVERGES: after an edit
    every public cache keeps answering the old value until its TTL runs out, so for a while the
    resolvers disagree and whichever one we happened to ask decides the verdict. A two-valued
    checker turns that into a false accusation ("your PTR is wrong" about a record that is right)
    and, worse, into FLAPPING — green, red, green — which spends the trust the rest of the list
    lives on. So every DNS check here asks all of them and reports agreement as a first-class fact.
"""
import concurrent.futures
import os
import re
import socket
import subprocess

MAIL_DOMAIN = os.environ.get("MAIL_DOMAIN", "local.test").strip().lower()
MAIL_FQDN = os.environ.get("MAIL_FQDN", "mail.local.test").strip().lower()
DKIM_SELECTOR = re.sub(r"[^a-z0-9-]", "-",
                       os.environ.get("MAIL_DKIM_SELECTOR", "mail").strip().lower()).strip("-") or "mail"
PUBLIC_IP_ENV = os.environ.get("MAIL_PUBLIC_IP", "").strip()
DKIM_DIR = os.environ.get("MAIL_DKIM_DIR", "/mailconfig/opendkim/keys")

# Whether the MTA is allowed to SEND over IPv6 — the same value mailserver-init writes into
# postfix-main.cf, read here so the checklist describes the server that exists rather than a
# server we would like to exist.
#
# Trust and IPv6 is the failure this exists to catch, and it is invisible by construction. PTR and
# SPF are facts about ONE address; a dual-stacked host has two, and a receiver checks whichever one
# we happened to connect from. On staging the v4 PTR was right and the v6 PTR was still the
# provider's default (srv908573.hstgr.cloud), while `v=spf1 mx ~all` covered only the MX host's A
# record — so any delivery that went out over v6 failed FCrDNS *and* SPF, and Gmail rejects that
# outright rather than spam-filing it. Nothing in the configuration chose v4; Postfix's address
# selection did, per remote MX, and it could have chosen otherwise on the next message.
#
# So: sending is IPv4-only by default and these checks stay silent, because there is nothing for
# the operator to do. Turn IPv6 sending ON and they appear — because that is the moment the v6 PTR
# and an SPF mechanism covering the v6 address stop being optional.
IPV6_SENDING = os.environ.get("MAIL_INET_PROTOCOLS", "ipv4").strip().lower() != "ipv4"
PUBLIC_IP6_ENV = os.environ.get("MAIL_PUBLIC_IP6", "").strip()

# A domain nobody can receive real mail at. `.test` is reserved by RFC 2606 exactly so it can never
# resolve publicly, so a deployment still on the default is a LOCAL one — not a misconfigured public
# one, and it must not be reported as a pile of failures.
LOCAL_SUFFIXES = (".test", ".localhost", ".local", ".invalid", ".example")


def is_local_only(domain=None):
    d = (domain or MAIL_DOMAIN)
    return d.endswith(LOCAL_SUFFIXES) or "." not in d


# ── DNS ───────────────────────────────────────────────────────────────────────
# dnspython is in requirements, but the checker must degrade rather than 500 if the image is ever
# built without it — a missing dependency should make the checks say "could not look up", not take
# the whole mail API's UI down.
try:
    import dns.resolver
    import dns.reversename
    _DNS = True
except Exception:                                       # pragma: no cover - import guard
    _DNS = False


# Ask the PUBLIC internet, never the container's own resolver.
#
# Docker's embedded DNS (127.0.0.11) answers for container hostnames before it forwards anything
# upstream — and the mail server's hostname IS the mail FQDN. So a lookup of mail.<domain> from
# inside this container returns the container's bridge address, and the A check reported:
#
#     [bad] כתובת השרת (A)   need 31.97.196.82   found 172.21.0.22
#
# on a deployment whose A record was perfectly correct. Every operator would have been sent to
# "fix" DNS that was already right — the single most damaging thing a setup checker can do, because
# it spends the trust that makes the rest of the checklist worth reading.
#
# The whole question this module asks is "what does the rest of the world see when it looks us up?",
# so consulting a resolver with a private view of the namespace is wrong on its own terms, not just
# inconvenient. Overridable for an air-gapped install that runs its own authoritative resolver.
PUBLIC_RESOLVERS = [s for s in
                    os.environ.get("MAIL_DNS_RESOLVERS", "1.1.1.1,8.8.8.8,9.9.9.9").split(",")
                    if s.strip()]

# The zone's own nameservers — ground truth, and the value every cache above is converging TOWARD.
# Used only as a tiebreaker and only in one direction (see _consensus); overridable off for an
# install that cannot reach arbitrary nameservers on port 53.
USE_AUTHORITATIVE = os.environ.get("MAIL_DNS_AUTHORITATIVE", "1").strip().lower() \
    not in ("0", "false", "no", "off")


def _resolver(nameservers=None):
    r = dns.resolver.Resolver()
    ns = nameservers if nameservers is not None else [s.strip() for s in PUBLIC_RESOLVERS]
    if ns:
        r.nameservers = list(ns)
    r.timeout, r.lifetime = 4.0, 6.0
    return r


def _unchunk(rec):
    """A TXT value over 255 bytes is stored as several strings that the reader concatenates. A DKIM
    2048-bit key is always over 255 bytes, so a checker that forgets this compares a joined record
    against a chunked one and reports a perfectly correct key as a mismatch."""
    return "".join(re.findall(r'"([^"]*)"', rec)) or rec


def _ask(name, rdtype, nameservers=None, txt=False):
    """(records, ttl, error) from ONE set of nameservers.

    Deliberately three-valued: [] means the name resolved and holds no such record (a real,
    actionable answer — "you have not published it"), while an error means we could not tell (do
    not accuse the operator of a mistake we did not observe)."""
    if not _DNS:
        return None, None, "dnspython not available in this image"
    try:
        ans = _resolver(nameservers).resolve(name, rdtype)
        # TXT is fetched VERBATIM here — quotes and all. Stripping them at this layer looked
        # harmless and silently destroyed every long record: a TXT over 255 bytes arrives as several
        # quoted strings, `"chunk1" "chunk2"`, and .strip('"') removes only the OUTERMOST pair,
        # leaving `chunk1" "chunk2`. Re-joining by matching quoted runs then finds only the single
        # space between them — so the value collapsed to " " and the key vanished.
        #
        # Every 2048-bit DKIM key is over 255 bytes. The result was that a correctly published DKIM
        # record was reported as MISSING, on a domain where mail was signing and verifying fine.
        # _unchunk() is the one place that joins, and it joins the WHOLE verbatim record.
        recs = [r.to_text() for r in ans]
        if txt:
            recs = [_unchunk(r) for r in recs]
        # The remaining lifetime of the answer we were handed — for a STALE answer this is exactly
        # "how much longer this resolver will keep lying", which is the only honest ETA we can give.
        return recs, getattr(getattr(ans, "rrset", None), "ttl", None), None
    except dns.resolver.NXDOMAIN:
        return [], None, None
    except dns.resolver.NoAnswer:
        return [], None, None
    except Exception as e:
        return None, None, "%s: %s" % (type(e).__name__, e)


def _query(name, rdtype):
    """(records, error) — the single-answer form, kept for callers that only need one opinion."""
    recs, _ttl, err = _ask(name, rdtype)
    return recs, err


def _txt(name):
    """TXT records, with the chunking undone."""
    recs, _ttl, err = _ask(name, "TXT", txt=True)
    return recs, err


# ── one question, every resolver ──────────────────────────────────────────────
def _ask_all(name, rdtype, servers, label=None, txt=False):
    """One answer per nameserver, asked in PARALLEL: three sequential lookups per record would
    triple the wall time of a screen an operator refreshes after every DNS edit."""
    servers = list(servers) or [None]
    out = [None] * len(servers)

    def one(i):
        recs, ttl, err = _ask(name, rdtype, [servers[i]] if servers[i] else None, txt=txt)
        out[i] = {"via": label or servers[i] or "system", "records": recs, "ttl": ttl, "error": err}

    if len(servers) == 1:
        one(0)
    else:
        with concurrent.futures.ThreadPoolExecutor(max_workers=min(len(servers), 8)) as ex:
            list(ex.map(one, range(len(servers))))
    return [v for v in out if v]


def _views(name, rdtype, txt=False):
    """What EACH configured public resolver answers."""
    return _ask_all(name, rdtype, [s.strip() for s in PUBLIC_RESOLVERS], txt=txt)


# Zone → nameserver addresses. Cleared at the top of every status() call: this endpoint is
# deliberately uncached, and a delegation that moved must not be answered from last hour's memory.
_ZONE_NS = {}


def _zone_nameservers(name):
    """Addresses of the nameservers authoritative for the closest zone at or above `name`.

    Walks up the labels because the zone cut is not knowable in advance — `82.196.97.31.in-addr.arpa`
    has no NS of its own, the delegation lives at `196.97.31.in-addr.arpa` (the VPS provider), and
    the same is true of `_dmarc.<domain>` versus `<domain>`."""
    parts = name.rstrip(".").split(".")
    for i in range(len(parts) - 1):
        zone = ".".join(parts[i:])
        if zone in _ZONE_NS:
            return _ZONE_NS[zone]
        recs, _t, _e = _ask(zone, "NS")
        if recs:
            ips = []
            for ns in recs:
                a, _t2, _e2 = _ask(ns.rstrip("."), "A")
                ips += a or []
            if ips:
                _ZONE_NS[zone] = ips
                return ips
    return []


def _authoritative_views(name, rdtype, txt=False):
    """What the zone's OWN nameservers answer — one view per server, `[]` if unobtainable.

    EVERY server, not the first one that responds, and the reason is measured rather than
    theoretical. The reverse zone for 31.97.196.82 is delegated to two anycast addresses, and while
    an rDNS edit was in flight the SAME address answered `mail.staging.digital-office.co.il` and
    `mail.digital-office.co.il` on consecutive queries — different backends of one "authoritative"
    server, mid-update. A tiebreaker that asks once and believes the answer is then just another
    coin flip, one layer closer to the source.

    Never raises and never argues: this is a hint, and a hint that cannot be obtained is simply
    absent. Everything here runs on someone else's port 53 — a firewall, a lame delegation or a
    provider that refuses direct queries must not change a verdict we could reach without it."""
    if not (_DNS and USE_AUTHORITATIVE):
        return []
    try:
        ips = _zone_nameservers(name)
        if not ips:
            return []
        return [v for v in _ask_all(name, rdtype, ips[:4], label="authoritative", txt=txt)
                if v["records"] is not None]
    except Exception:                                   # pragma: no cover - best-effort tiebreaker
        return []


def _consensus(name, rdtype, matches, txt=False, render=None):
    """Ask every resolver and report whether they AGREE — the three-valued answer this module needs.

        state="ok"           every resolver that answered matches what we expect
        state="propagating"  they DISAGREE and at least one already matches: the record is right and
                             the stale caches are on their way out. Not a fault, not the operator's
                             to fix, and not something to count against them.
        state="no"           nobody matches — a real problem, reported as loudly as before
        state="unknown"      nobody could be asked (say so; never guess)

    The zone's OWN nameservers are consulted only when no public resolver matches, and they can
    only ever UPGRADE that to `propagating`. The asymmetry is the whole safety property, and the
    tempting symmetric version was tried and measured here first: letting a mismatching
    authoritative answer DOWNGRADE a `propagating` sounds strictly more correct — a stale cache
    that happens to match, over a zone that says otherwise, is a value on its way out — and it is
    unimplementable against real infrastructure. The provider's two "authoritative" reverse-zone
    servers are anycast, and mid-edit the same address answered the new name and the old one on
    consecutive queries. A downgrade rule on top of that samples a coin and calls a correct,
    already-published record broken. Which leaves the honest ordering: evidence that the expected
    value EXISTS somewhere authoritative or cached outweighs a sample that failed to find it, and a
    check only goes red when nothing anywhere has it.

    So: a unanimous public `ok` is never overturned (and costs no extra lookups), a record the zone
    has but no cache does yet is rescued, and an authoritative query that cannot be made at all
    (firewall, lame delegation, MAIL_DNS_AUTHORITATIVE off) changes nothing — the public-resolver
    verdict stands exactly as it would have."""
    render = render or (lambda recs: recs)
    views = _views(name, rdtype, txt=txt)
    usable = [v for v in views if v["records"] is not None]
    if not usable:
        return {"state": "unknown", "records": None, "observed": "—", "ttl": None,
                "error": next((v["error"] for v in views if v["error"]), "no resolver"),
                "groups": []}

    flags = [(v, bool(matches(v["records"]))) for v in usable]
    agree = [v for v, m in flags if m]
    disagree = [v for v, m in flags if not m]
    shown = list(usable)
    state = "ok" if not disagree else ("propagating" if agree else "no")
    truth = None

    if state == "no":
        av = _authoritative_views(name, rdtype, txt=txt)
        hits = [v for v in av if matches(v["records"])]
        if hits:
            state, agree, shown, truth = "propagating", agree + hits, shown + av, hits[0]["records"]
        elif av:
            # No rescue, but the zone's own answer is still the best thing to decide `bad` versus
            # `missing` from, and worth showing: "the nameservers themselves have nothing here" is a
            # different sentence to an operator than "the caches have not caught up".
            shown, truth = shown + av[:1], av[0]["records"]

    # What to report as OBSERVED. When everyone agrees this is just the value; when they do not, it
    # must name WHO saw what, because "some resolvers still have the old value" is unreadable
    # without it and is the one fact that distinguishes this state from a broken record.
    groups = []
    for v in shown:
        vals = [str(x) for x in (render(v["records"]) or [])]
        key = tuple(vals)
        hit = next((g for g in groups if g["key"] == key), None)
        if hit:
            if v["via"] not in hit["via"]:      # two of the zone's nameservers are one source
                hit["via"].append(v["via"])
        else:
            groups.append({"key": key, "value": ", ".join(vals) or "—", "via": [v["via"]]})
    observed = (groups[0]["value"] if len(groups) == 1
                else " · ".join("%s (%s)" % (g["value"], ", ".join(g["via"])) for g in groups))

    # The representative record set — what `bad` vs `missing` is decided from, so it must be the
    # most authoritative thing we have: the zone's own answer when we got one, otherwise a matching
    # view (so `ok` reports the good value), otherwise the first mismatching one (so a failure
    # reports what is actually published).
    records = truth if truth is not None else (agree[0] if agree else disagree[0])["records"]
    # Worst-case wait = the longest TTL still held by a resolver that has NOT caught up yet.
    ttls = [v["ttl"] for v in disagree if v["ttl"]]
    return {"state": state, "records": records, "observed": observed or "—",
            "ttl": max(ttls) if ttls else None, "error": None, "groups": groups}


def _dur(sec):
    """A TTL in words. `82186` is not an amount of time to anyone reading a checklist."""
    if sec is None:
        return None
    if sec < 90:
        return "%d שניות" % sec
    if sec < 5400:
        return "כ-%d דקות" % round(sec / 60.0)
    return "כ-%d שעות" % round(sec / 3600.0)


def _propagating_detail(con):
    """The words for a record that is RIGHT and not yet everywhere.

    Says three things, because leaving any of them out puts the operator back where they started:
    the record is correct, there is nothing to do, and roughly how long until the stragglers expire.
    """
    txt = ("הרשומה מוגדרת נכון — חלק משרתי ה-DNS בעולם עדיין מחזירים את הערך הקודם מהמטמון שלהם. "
           "אין מה לתקן ואין צורך לפרסם שוב.")
    d = _dur(con.get("ttl"))
    return txt + (" מטמוני DNS מתרעננים לכל היותר בתוך ה-TTL של הרשומה (כאן %s); בדרך כלל דקות עד "
                  "שעות ספורות." % d if d else
                  " מטמוני DNS מתרעננים לכל היותר בתוך ה-TTL של הרשומה — בדרך כלל דקות עד שעות ספורות.")


def _status_of(con, present):
    """A consensus → one checklist status. `present` distinguishes the two ways of not matching:
    something IS published and it is wrong (`bad`, more urgent because it looks done) versus nothing
    is published at all (`missing`, a plain to-do)."""
    return ("ok" if con["state"] == "ok" else
            "propagating" if con["state"] == "propagating" else
            "bad" if present else "missing")


# ── the DKIM public key this server actually signs with ───────────────────────
def dkim_public_record(domain=None):
    """(p= value, full TXT value, path) read off the generated key, or (None, None, None).

    opendkim-genkey writes a BIND-format .txt like:
        sel._domainkey IN TXT ( "v=DKIM1; h=sha256; k=rsa; "
          "p=MIIBIjANBg...IDAQAB" )  ; ----- DKIM key sel for example.com
    """
    d = domain or MAIL_DOMAIN
    path = os.path.join(DKIM_DIR, d, "%s.txt" % DKIM_SELECTOR)
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            raw = fh.read()
    except OSError:
        return None, None, None
    joined = "".join(re.findall(r'"([^"]*)"', raw))
    if not joined:
        return None, None, path
    m = re.search(r"p=([A-Za-z0-9+/=]+)", joined)
    return (m.group(1) if m else None), joined.strip(), path


def _p_of(txt):
    m = re.search(r"p=([A-Za-z0-9+/=]+)", txt or "")
    return m.group(1) if m else None


# ── host-level facts ──────────────────────────────────────────────────────────
def _tcp_open(host, port, timeout=4.0):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except Exception:
        return False


def public_ip():
    """The address the internet sees. Configured first — on a VPS the operator knows it and a
    configured value cannot be wrong. Auto-detection is a fallback and is clearly labelled, because
    a NAT'd laptop 'detecting' its router's address would produce a confidently wrong PTR check."""
    if PUBLIC_IP_ENV:
        return PUBLIC_IP_ENV, "configured"
    if not _DNS:
        return None, "unknown"
    try:
        # Resolver-based, not an HTTP call to a third party: this asks OpenDNS what address the
        # query arrived from. No TLS, no dependency on someone's uptime, and it cannot be a redirect.
        ans = _resolver(["208.67.222.222", "208.67.220.220"]).resolve("myip.opendns.com", "A")
        return ans[0].to_text(), "detected"
    except Exception:
        return None, "unknown"


def public_ip6():
    """The IPv6 address this server would send from — same contract as public_ip().

    CONFIGURED first, then the AAAA of our own mail FQDN, and otherwise nothing. There is no
    detection step: asking a resolver "what address did this query come from" over IPv6 requires
    IPv6 to already work from inside this container, which is precisely what is in question. An
    address we guessed wrong would produce a confident PTR verdict about somebody else's address,
    and this module's whole discipline is that a wrong answer costs more than no answer."""
    if PUBLIC_IP6_ENV:
        return PUBLIC_IP6_ENV, "configured"
    if not _DNS:
        return None, "unknown"
    try:
        ans = _resolver().resolve(MAIL_FQDN, "AAAA")
        return ans[0].to_text(), "derived"          # from the AAAA the operator published for us
    except Exception:
        return None, "unknown"


def _v6(addr):
    """An IPv6 address as bytes, or None. Text comparison is wrong here: 2a02:4780:28:cb4c::1 and
    2a02:4780:28:cb4c:0:0:0:1 are the same address and only one of them is what someone typed."""
    try:
        return socket.inet_pton(socket.AF_INET6, (addr or "").strip())
    except Exception:
        return None


def _in6(addr_bytes, cidr):
    """Is `addr_bytes` inside `cidr` (an ip6 mechanism's argument, with or without a /prefix)?
    Operators write ip6:2a02:4780:28:cb4c::/64 at least as often as a single address, and treating
    that as "does not cover us" would send someone to fix a record that is already correct."""
    net, _, bits = cidr.partition("/")
    n = _v6(net)
    if n is None:
        return False
    try:
        bits = int(bits) if bits else 128
    except ValueError:
        return False
    if not 0 <= bits <= 128:
        return False
    keep, rem = divmod(bits, 8)
    if addr_bytes[:keep] != n[:keep]:
        return False
    if rem and (addr_bytes[keep] ^ n[keep]) >> (8 - rem):
        return False
    return True


def _aaaa(name):
    if not _DNS:
        return []
    try:
        return [r.to_text() for r in _resolver().resolve(name, "AAAA")]
    except Exception:
        return []


def _check(cid, title, status, detail, expected=None, observed=None, record=None, fix=None):
    """One line of the checklist. `record` is a publishable DNS entry the UI shows with a copy
    button — the difference between "SPF is missing" and something the operator can act on."""
    return {"id": cid, "title": title, "status": status, "detail": detail,
            "expected": expected, "observed": observed, "record": record, "fix": fix}


# ── the checks ────────────────────────────────────────────────────────────────
def status(imap_probe=None, mailbox_list=None):
    """The full picture. `imap_probe` is an optional callable returning (ok, reason) for the local
    mailbox, and `mailbox_list` an optional callable returning the domain's mailboxes — both
    injected by the caller so this module does not import a backend and this stays testable.

    Status vocabulary — deliberately five, not two:
      ok           verified true
      propagating  verified RIGHT, and not yet visible everywhere; the resolvers disagree and at
                   least one of them already has the correct value. Nothing to do, nothing to
                   count: it does not block `ready` and is not part of `remaining`, because an
                   operator who did the work correctly must not be handed a to-do for it.
      missing      verified absent; the operator has something to publish
      bad          present but WRONG; more urgent than missing, because it looks done
      unknown      could not be determined from here (say so; never guess)
    """
    _ZONE_NS.clear()
    domain, fqdn = MAIL_DOMAIN, MAIL_FQDN
    local_only = is_local_only(domain)
    ip, ip_src = public_ip()
    checks = []

    # The mailboxes that exist at this domain. Reported HERE, in the setup answer, rather than on a
    # screen of its own, because the two facts only mean anything together: an address is worth
    # something exactly insofar as the domain's records are published, and the records are worth
    # something exactly insofar as somebody has an address at it. It is also the honest end of the
    # growth story — once this list can grow with no new row above it, onboarding a person is
    # finished work rather than a DNS ticket.
    mb = {"available": False, "count": 0, "addresses": []}
    if mailbox_list:
        try:
            mb = mailbox_list() or mb
        except Exception:
            pass

    # 1. the mailbox itself — the only check that is meaningful even on a laptop
    if imap_probe:
        ok, reason = imap_probe()
        checks.append(_check(
            "mailbox", "תיבת הדואר המקומית", "ok" if ok else "bad",
            "השרת המקומי עונה ותיבת הדואר פעילה." if ok
            else "שרת הדואר המקומי אינו עונה: %s" % (reason or "לא ידוע"),
            fix=None if ok else "בדוק שהשירות mailserver רץ ותקין."))

    # 1b. the mailboxes at this domain. Not a DNS fact and not a to-do — a COUNT, and the point it
    #     makes is that this number can grow without anything above or below it changing. It is
    #     `unknown`, never `bad`, when the writer service cannot be reached: not being able to LIST
    #     the mailboxes says nothing about whether they receive mail, and painting it red would
    #     claim a delivery problem that has not been observed.
    if mailbox_list:
        addrs = mb.get("addresses") or []
        checks.append(_check(
            "mailboxes", "תיבות דואר בדומיין",
            "ok" if mb.get("available") and addrs else ("unknown" if not mb.get("available") else "bad"),
            # (one mailbox is «תיבת דואר אחת» — a fresh install has exactly one, and read «קיימות 1 תיבות»)
            (("קיימת תיבת דואר אחת." if len(addrs) == 1 else "קיימות %d תיבות דואר." % len(addrs))
             + " הוספת תיבה נוספת אינה דורשת שום שינוי ב-DNS — הרשומות של הדומיין כבר מכסות כל כתובת בו.") if addrs
            else ("לא ניתן לקרוא את רשימת התיבות כרגע." if not mb.get("available")
                  else "לא הוגדרה אף תיבת דואר."),
            observed=", ".join(addrs) or "—",
            fix=None if addrs else ("שירות ניהול התיבות (mailboxd) אינו עונה." if not mb.get("available")
                                    else "הוסף תיבה במסך ניהול תיבות הדואר.")))

    # 2. DKIM — check the KEY before the DNS record. A missing key is our bug; a missing record is
    #    the operator's to-do. Reporting "publish this record" when no key exists sends them to
    #    paste a value that does not exist yet.
    pub, full_txt, key_path = dkim_public_record(domain)
    dkim_name = "%s._domainkey.%s" % (DKIM_SELECTOR, domain)
    if not pub:
        checks.append(_check(
            "dkim_key", "מפתח החתימה (DKIM)", "bad",
            "לא נוצר מפתח חתימה עבור %s. השירות ישלח דואר לא חתום, שסביר שייחסם." % domain,
            fix="הפעל מחדש את שירות המייל — המפתח נוצר אוטומטית באתחול."))
    else:
        checks.append(_check(
            "dkim_key", "מפתח החתימה (DKIM)", "ok",
            "קיים מפתח חתימה פרטי עבור %s (מזהה: %s)." % (domain, DKIM_SELECTOR),
            observed=key_path))

    # 3–7 are DNS, and DNS is only meaningful for a real domain.
    if local_only:
        checks.append(_check(
            "public", "דואר ציבורי", "unknown",
            "ההתקנה משתמשת בדומיין מקומי (%s), ולכן אינה יכולה לקבל או לשלוח דואר מהאינטרנט. "
            "כל השאר עובד: דואר פנימי, חיפוש, תוויות ואוטומציות." % domain,
            fix="כדי לפתוח דואר ציבורי, הגדר MAIL_DOMAIN ו-MAIL_FQDN לדומיין אמיתי ופרסם את הרשומות."))
        return {"domain": domain, "fqdn": fqdn, "selector": DKIM_SELECTOR, "public_ip": ip,
                "public_ip_source": ip_src, "mode": "local", "ready": True, "checks": checks,
                "mailboxes": mb}

    # 3. MX — where other servers deliver
    want_mx = fqdn.rstrip(".")
    _hosts = lambda recs: [m.split()[-1].rstrip(".").lower() for m in recs]
    con = _consensus(domain, "MX", lambda recs: want_mx in _hosts(recs), render=_hosts)
    if con["state"] == "unknown":
        checks.append(_check("mx", "רשומת MX", "unknown", "לא ניתן לבדוק: %s" % con["error"]))
    else:
        st = _status_of(con, bool(con["records"]))
        checks.append(_check(
            "mx", "רשומת MX", st,
            _propagating_detail(con) if st == "propagating"
            else "שרתי דואר אחרים שולחים אליך לפי רשומה זו.",
            expected=want_mx, observed=con["observed"],
            record={"type": "MX", "name": domain, "value": "10 %s." % want_mx}))

    # 4. A — the MX name must resolve to this machine
    if not ip:
        # No expectation to compare against, so there is nothing to reach consensus ABOUT: report
        # what is published and say plainly that we cannot judge it.
        a, err = _query(fqdn, "A")
        checks.append(_check("a", "כתובת השרת (A)", "unknown",
                             "לא ניתן לבדוק: %s" % err if a is None
                             else "לא ידועה כתובת ה-IP הציבורית של השרת.",
                             observed=", ".join(a or []) or "—",
                             fix=None if a is None else "הגדר MAIL_PUBLIC_IP בקובץ הסביבה."))
    else:
        con = _consensus(fqdn, "A", lambda recs: ip in recs)
        if con["state"] == "unknown":
            checks.append(_check("a", "כתובת השרת (A)", "unknown",
                                 "לא ניתן לבדוק: %s" % con["error"]))
        else:
            st = _status_of(con, bool(con["records"]))
            checks.append(_check(
                "a", "כתובת השרת (A)", st,
                _propagating_detail(con) if st == "propagating"
                else "השם %s חייב להצביע על שרת זה." % fqdn,
                expected=ip, observed=con["observed"],
                record={"type": "A", "name": fqdn, "value": ip}))

    # 5. SPF — who is allowed to send as this domain
    want = "v=spf1 mx ~all"
    _spf_of = lambda recs: next((t for t in recs if t.lower().startswith("v=spf1")), None)

    # The question is "does this record authorise THIS server", not "does it look like the one we
    # would have written". A first pass accepted only `mx` or `ip4:<our ip>` and therefore called
    #     v=spf1 a:mail.digital-office.co.il -all
    # BAD — a record that names our host explicitly and is STRICTER than the suggestion (-all
    # rather than ~all). Telling an operator to replace that with something weaker is worse than
    # saying nothing, so `a:` mechanisms are resolved and compared against our address too.
    def _authorises(rec):
        toks = (rec or "").split()
        if "mx" in toks or "a" in toks:
            return True                          # bare `a`/`mx` = "the domain's own A/MX records"
        if ip and any(t == "ip4:%s" % ip for t in toks):
            return True
        for t in toks:
            if t.startswith("a:") and _DNS:
                try:
                    if ip and ip in [x.to_text() for x in _resolver().resolve(t[2:], "A")]:
                        return True
                except Exception:
                    pass
        return False

    con = _consensus(domain, "TXT", lambda recs: _authorises(_spf_of(recs)), txt=True,
                     render=lambda recs: [_spf_of(recs) or "—"])
    if con["state"] == "unknown":
        checks.append(_check("spf", "רשומת SPF", "unknown", "לא ניתן לבדוק: %s" % con["error"]))
    else:
        spf = _spf_of(con["records"])
        st = _status_of(con, bool(spf))
        detail = (_propagating_detail(con) if st == "propagating" else
                  "השרת מורשה לשלוח בשם הדומיין." if st == "ok" else
                  "קיימת רשומת SPF שאינה כוללת את השרת הזה." if st == "bad" else
                  "ללא SPF, נמענים רבים יסמנו את הדואר כספאם.")
        checks.append(_check("spf", "רשומת SPF", st, detail, expected=want,
                             observed=con["observed"],
                             record={"type": "TXT", "name": domain, "value": want}))

    # 6. DKIM record vs the key we actually hold
    if pub:
        want_val = full_txt or "v=DKIM1; h=sha256; k=rsa; p=%s" % pub
        _pub_of = lambda recs: _p_of(next((t for t in recs if "p=" in t), None))
        con = _consensus(dkim_name, "TXT", lambda recs: _pub_of(recs) == pub, txt=True,
                         render=lambda recs: [(_pub_of(recs) or "—")[:32] + "…"])
        if con["state"] == "unknown":
            checks.append(_check("dkim", "פרסום מפתח DKIM", "unknown",
                                 "לא ניתן לבדוק: %s" % con["error"],
                                 record={"type": "TXT", "name": dkim_name, "value": want_val}))
        else:
            st = _status_of(con, bool(_pub_of(con["records"])))
            detail = (_propagating_detail(con) if st == "propagating" else
                      "המפתח שפורסם תואם למפתח שבו השרת חותם." if st == "ok" else
                      # The nastiest of the four: everything looks configured, every signature fails.
                      "המפתח שפורסם אינו תואם למפתח של השרת — כל החתימות ייכשלו." if st == "bad" else
                      "המפתח קיים בשרת אך טרם פורסם ב-DNS, ולכן החתימה אינה נבדקת.")
            checks.append(_check("dkim", "פרסום מפתח DKIM", st, detail,
                                 expected=pub[:32] + "…", observed=con["observed"],
                                 record={"type": "TXT", "name": dkim_name, "value": want_val}))

    # 7. DMARC — what a receiver should do when the above fail
    want_dmarc = "v=DMARC1; p=none; rua=mailto:postmaster@%s" % domain
    _dmarc_of = lambda recs: next((t for t in recs if t.lower().startswith("v=dmarc1")), None)
    con = _consensus("_dmarc.%s" % domain, "TXT", lambda recs: bool(_dmarc_of(recs)), txt=True,
                     render=lambda recs: [_dmarc_of(recs) or "—"])
    if con["state"] == "unknown":
        checks.append(_check("dmarc", "רשומת DMARC", "unknown", "לא ניתן לבדוק: %s" % con["error"]))
    else:
        # Never `bad`: any v=DMARC1 record is a policy, and we are in no position to call somebody
        # else's policy wrong — only its absence is a to-do.
        st = _status_of(con, False)
        checks.append(_check(
            "dmarc", "רשומת DMARC", st,
            _propagating_detail(con) if st == "propagating"
            else "מגדירה מה יעשה נמען כאשר בדיקה נכשלת, ומשפרת את אמון השולח.",
            expected=want_dmarc, observed=con["observed"],
            record={"type": "TXT", "name": "_dmarc.%s" % domain, "value": want_dmarc}))

    # 8. PTR — reverse DNS, the one record the DOMAIN registrar cannot set. It is also the one most
    #    likely to be caught mid-propagation: it is edited at the VPS provider long after the
    #    forward records were published, and the reverse zone's TTLs are not ours to shorten.
    if ip and _DNS:
        _names = lambda recs: [r.rstrip(".").lower() for r in recs]
        con = _consensus(dns.reversename.from_address(ip).to_text(), "PTR",
                         lambda recs: fqdn in _names(recs), render=_names)
        if con["state"] == "unknown":
            st, detail = "unknown", "לא ניתן לבדוק את השם ההפוך: %s" % con["error"]
        else:
            st = _status_of(con, bool(con["records"]))
            detail = (_propagating_detail(con) if st == "propagating" else
                      "שם הפוך תקין — גורם מרכזי באמון מול Gmail." if st == "ok" else
                      "השם ההפוך אינו תואם לשם השרת; חלק מהנמענים ידחו את הדואר." if st == "bad" else
                      "לא הוגדר שם הפוך לכתובת השרת.")
        checks.append(_check(
            "ptr", "שם הפוך (PTR)", st, detail, expected=fqdn, observed=con["observed"],
            # Not a DNS record the operator can publish at their registrar — it belongs to whoever
            # owns the IP. Saying "add a TXT" here would send them somewhere that cannot help them.
            # And when it is merely propagating there is nothing to send them to at all.
            fix=None if st == "propagating" else
            "נקבע אצל ספק השרת (Hostinger/VPS) בהגדרות ה-rDNS של הכתובת, ולא אצל רשם הדומיין."))

    # 8b. IPv6 — ONLY when this deployment is configured to send over it.
    #
    # Two rows, not one, and they mirror `ptr` and `spf` deliberately: the failure is that the two
    # facts every receiver checks are per-ADDRESS, and turning IPv6 on quietly adds a second address
    # that neither of them has been made true for. The operator who set MAIL_INET_PROTOCOLS=all is
    # the only person these rows are for, and they need to know WHICH of the two is missing, because
    # they are fixed in two different control panels — the PTR at the VPS provider, the SPF at the
    # registrar. A merged "IPv6 is not ready" would name neither.
    #
    # Silent by default. With IPv4-only sending there is no v6 address in play, so a permanently
    # green "IPv6: not applicable" row would be pure noise — and a checklist people scroll past is
    # how the DKIM bug survived.
    if IPV6_SENDING:
        ip6, ip6_src = public_ip6()
        if not ip6 or not _DNS:
            checks.append(_check(
                "ipv6", "שליחה ב-IPv6", "bad",
                "השרת מוגדר לשלוח גם ב-IPv6, אך כתובת ה-IPv6 שלו אינה ידועה — לא ניתן לאמת PTR ו-SPF עבורה.",
                fix="הגדר MAIL_PUBLIC_IP6, או החזר את השליחה ל-IPv4 בלבד (MAIL_INET_PROTOCOLS=ipv4)."))
        else:
            src6 = "" if ip6_src == "configured" else " (נגזר מרשומת ה-AAAA)"

            # PTR of the v6 address. Same consensus machinery as the v4 one — a reverse zone edited
            # at the provider propagates on TTLs nobody here controls, and calling that "wrong"
            # instead of "propagating" is the flapping this module exists to avoid.
            _names = lambda recs: [r.rstrip(".").lower() for r in recs]
            con = _consensus(dns.reversename.from_address(ip6).to_text(), "PTR",
                             lambda recs: fqdn in _names(recs), render=_names)
            if con["state"] == "unknown":
                st6, d6 = "unknown", "לא ניתן לבדוק את השם ההפוך ל-IPv6: %s" % con["error"]
            else:
                st6 = _status_of(con, bool(con["records"]))
                d6 = (_propagating_detail(con) if st6 == "propagating" else
                      "שם הפוך תקין גם ב-IPv6." if st6 == "ok" else
                      "השם ההפוך של כתובת ה-IPv6 אינו תואם לשם השרת — Gmail דוחה דואר IPv6 כזה, ולא רק מסמן אותו כספאם." if st6 == "bad" else
                      "לא הוגדר שם הפוך לכתובת ה-IPv6.")
            checks.append(_check(
                "ptr6", "שם הפוך ל-IPv6 (PTR)", st6, d6 + src6, expected=fqdn,
                observed=con["observed"],
                fix=None if st6 in ("ok", "propagating") else
                "נקבע אצל ספק השרת ב-rDNS של כתובת ה-IPv6 — רשומה נפרדת מזו של ה-IPv4. "
                "אם אין גישה להגדיר אותה, החזר את השליחה ל-IPv4 בלבד (MAIL_INET_PROTOCOLS=ipv4)."))

            # SPF for the v6 address. `mx` and `a` are NOT assumed to cover it: they expand to the
            # A *and* AAAA records of those hosts, so whether they authorise this address is a
            # question about what is published, not about what the mechanism is called. That
            # assumption is the whole bug — "v=spf1 mx ~all" reads as complete and covers only v4
            # for as long as the MX host has no AAAA.
            b6 = _v6(ip6)

            def _authorises6(rec):
                toks = (rec or "").split()
                if b6 is None:
                    return False
                for t in toks:
                    low = t.lower()
                    if low.startswith("ip6:") and _in6(b6, t[4:]):
                        return True
                    if low == "a" and any(_v6(x) == b6 for x in _aaaa(domain)):
                        return True
                    if low.startswith("a:") and any(_v6(x) == b6 for x in _aaaa(t[2:])):
                        return True
                    if low == "mx" or low.startswith("mx:"):
                        host = t[3:] if low.startswith("mx:") else None
                        hosts = [host] if host else []
                        if not hosts:
                            try:
                                hosts = [r.exchange.to_text().rstrip(".")
                                         for r in _resolver().resolve(domain, "MX")]
                            except Exception:
                                hosts = []
                        if any(_v6(x) == b6 for h in hosts for x in _aaaa(h)):
                            return True
                return False

            want6 = "v=spf1 mx ip6:%s ~all" % ip6
            con = _consensus(domain, "TXT", lambda recs: _authorises6(_spf_of(recs)), txt=True,
                             render=lambda recs: [_spf_of(recs) or "—"])
            if con["state"] == "unknown":
                checks.append(_check("spf6", "SPF עבור IPv6", "unknown",
                                     "לא ניתן לבדוק: %s" % con["error"]))
            else:
                st6 = _status_of(con, bool(_spf_of(con["records"])))
                checks.append(_check(
                    "spf6", "SPF עבור IPv6", st6,
                    (_propagating_detail(con) if st6 == "propagating" else
                     "כתובת ה-IPv6 מורשית לשלוח בשם הדומיין." if st6 == "ok" else
                     "רשומת ה-SPF אינה מכסה את כתובת ה-IPv6 של השרת. מנגנוני mx/a מכסים IPv6 רק אם פורסמה רשומת AAAA."),
                    expected=want6, observed=con["observed"],
                    record={"type": "TXT", "name": domain, "value": want6}))

    # 9. inbound 25 — the check that actually caught the firewall bug
    #    Honest scope: from inside the container we can prove Postfix ANSWERS, and we can prove this
    #    host can REACH the internet on 25. We cannot prove the internet reaches us — that needs an
    #    external prober — so it is reported as two separate, individually true facts rather than
    #    one confident guess.
    checks.append(_check(
        "smtp_local", "שרת ה-SMTP מגיב", "ok" if _tcp_open("mailserver", 25) else "bad",
        "Postfix מאזין ומקבל חיבורים בתוך המערכת.",
        fix=None if _tcp_open("mailserver", 25) else "שירות ה-mailserver אינו עונה על פורט 25."))
    out25 = _tcp_open("gmail-smtp-in.l.google.com", 25, timeout=6.0)
    checks.append(_check(
        "smtp_outbound", "יציאה לאינטרנט (פורט 25)", "ok" if out25 else "bad",
        "נדרש כדי לשלוח דואר לשרתים אחרים." if out25
        else "הרשת חוסמת יציאה בפורט 25 — לא ניתן לשלוח דואר החוצה. ספקי ענן רבים חוסמים זאת כברירת מחדל.",
        fix=None if out25 else "בקש מספק השרת לפתוח יציאה בפורט 25, או השתמש ב-relay חיצוני."))

    # `propagating` is deliberately NOT in this list. A record that is published correctly is done
    # work, and counting it would tell an operator who did everything right that they have one thing
    # left — while a stale cache somewhere else in the world flips the number back and forth.
    blocking = [c for c in checks if c["status"] in ("missing", "bad")]
    return {"domain": domain, "fqdn": fqdn, "selector": DKIM_SELECTOR, "public_ip": ip,
            "public_ip_source": ip_src, "mode": "public", "ready": not blocking,
            "remaining": len(blocking),
            "propagating": len([c for c in checks if c["status"] == "propagating"]),
            "checks": checks, "mailboxes": mb}
