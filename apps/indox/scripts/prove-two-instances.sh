#!/usr/bin/env bash
#
# PHASE 6b — prove two INDOX instances reconcile in parallel without leaking into each other.
#
# The brief was explicit that "tenancy exists" is not the deliverable. This script is: it stands up a
# second instance beside the live one, gives it its own target table, settings, companies, tag rules
# and registry, runs the scanner ONCE so both reconcile in the same pass, and then checks a canary
# in each direction.
#
# The collision it is built around is deliberate. Instance B's pipe is called `drive-gdoc` — the same
# name as instance A's — because that is what duplicating an INDOX actually gives you. `sync_ledger`
# is keyed (source, platform_id), so un-namespaced the two instances would share ledger rows and each
# would read the other's deliveries as already done. One client's documents would silently never
# arrive, with both boards green. If the namespacing regressed, THIS is the test that goes red.
#
# Read-only with respect to instance A: everything it creates is prefixed and dropped at the end.
#
#   usage:  apps/indox/scripts/prove-two-instances.sh [--keep]
#
set -uo pipefail

A_INST="incoming-documents-main"
B_INST="indox-proof-b"
B_TABLE="incoming_documents_proof_b"
PIPE="drive-gdoc"                    # SAME name in both instances — the whole point
KEEP="${1:-}"

SB=$(docker ps --format '{{.Names}}' | grep -m1 supabase-db) || true
N8N=$(docker ps --format '{{.Names}}' | grep -m1 '^n8n-shlomo' ) || true
: "${SB:?supabase-db container not found — is the stack up?}"

q()  { docker exec "$SB" psql -U postgres -d postgres -tAqc "$1"; }
sql() { docker exec -i "$SB" psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q -f -; }

pass=0; fail=0
check() { # check <label> <actual> <expected>
  if [ "$2" = "$3" ]; then printf '   PASS  %-52s %s\n' "$1" "$2"; pass=$((pass+1))
  else printf '   FAIL  %-52s got=%s want=%s\n' "$1" "$2" "$3"; fail=$((fail+1)); fi
}

cleanup() {
  [ "$KEEP" = "--keep" ] && { echo; echo "--keep: leaving $B_INST in place"; return; }
  sql <<SQL >/dev/null 2>&1
drop table if exists public.$B_TABLE;
delete from public.settings   where instance = '$B_INST';
delete from public.companies  where instance = '$B_INST';
delete from public.tag_rules  where instance = '$B_INST';
delete from public.sync_ledger  where source like '$B_INST/%';
delete from public.sync_cursor  where source like '$B_INST/%';
delete from public.sync_attempt where source like '$B_INST/%';
delete from public.drive_files where id like '_proof_%';
delete from public.sync_ledger where platform_id like '_proof_%';
SQL
  echo; echo "cleaned up $B_INST"
}
trap cleanup EXIT

echo "════════ PHASE 6b — two instances, one scanner pass ════════"
echo "  A = $A_INST   (live)"
echo "  B = $B_INST   (created here, dropped on exit)"
echo "  both define a pipe called '$PIPE' — the collision under test"
echo

# ─────────────────────────────────────────────────────────────────────────────
echo "── 1. stand up instance B: its own table, settings, companies, tag rules"
# The target table is what stays table-per-instance: 84 columns that differ per client, and a
# dedupe constraint whose semantics would have to change under a discriminator column.
sql <<SQL
create table if not exists public.$B_TABLE (like public.incoming_documents including all);
delete from public.settings  where instance = '$B_INST';
delete from public.companies where instance = '$B_INST';
delete from public.tag_rules where instance = '$B_INST';
insert into public.settings  (instance, key, value) values
  ('$B_INST', 'canary',        'B-ONLY'),
  ('$B_INST', 'docs_source_folder_id', '_proof_b_src');
insert into public.companies (instance, "שם חברה", "מזהה 1") values
  ('$B_INST', 'Proof B Co', '900000001');
-- id is GENERATED BY DEFAULT as identity, and this table's existing rows were inserted with
-- explicit ids — so the sequence sits behind the data and a plain insert collides on the primary
-- key. Taking max(id)+1 sidesteps that without reseeding a sequence this script does not own.
-- (No backticks in this heredoc: it is unquoted so that $B_INST interpolates, which means the
--  shell would run anything backticked here as a command before psql ever saw it.)
insert into public.tag_rules (id, instance, "KEY", "LABEL")
  select coalesce(max(id),0)+1, '$B_INST', 'PROOF_B', 'proof-b-label' from public.tag_rules;
SQL
check "B has its own settings"  "$(q "select count(*) from public.settings  where instance='$B_INST';")" "2"
check "B has its own companies" "$(q "select count(*) from public.companies where instance='$B_INST';")" "1"
check "B has its own tag_rules" "$(q "select count(*) from public.tag_rules where instance='$B_INST';")" "1"

# ─────────────────────────────────────────────────────────────────────────────
echo
echo "── 2. a canary in each instance's config, and each instance's own registry"
# A's canary must never be visible to B and vice versa. This is the leakage test in its simplest
# form — before any pipeline runs at all, does a scoped read see only its own instance?
q "insert into public.settings (instance,key,value) values ('$A_INST','canary','A-ONLY')
   on conflict (instance,key) do update set value='A-ONLY';" >/dev/null

A_SEES=$(q "select value from public.settings where instance='$A_INST' and key='canary';")
B_SEES=$(q "select value from public.settings where instance='$B_INST' and key='canary';")
check "A's canary reads A-ONLY"          "$A_SEES" "A-ONLY"
check "B's canary reads B-ONLY"          "$B_SEES" "B-ONLY"
check "A cannot see B's rows"            "$(q "select count(*) from public.settings where instance='$A_INST' and value='B-ONLY';")" "0"
check "B cannot see A's rows"            "$(q "select count(*) from public.settings where instance='$B_INST' and value='A-ONLY';")" "0"

# B's registry: one v3 drive pipe, SAME NAME as A's, its own folders, its own connection.
q "insert into public.settings (instance,key,value) values ('$B_INST','sync_registry',
   '[{\"name\":\"$PIPE\",\"source\":\"drive\",\"engine\":\"v3\",\"enabled\":true,\"connection\":\"proof-b-conn\",
      \"pairs\":[{\"to_sync\":\"_proof_b_src\",\"synced\":\"_proof_b_done\",\"failed\":\"_proof_b_fail\"}],
      \"batch\":{\"take\":5}}]')
   on conflict (instance,key) do update set value=excluded.value;" >/dev/null
echo "   B registry: 1 pipe named '$PIPE' on connection proof-b-conn"

# ─────────────────────────────────────────────────────────────────────────────
echo
echo "── 3. THE LEDGER KEY — the constraint that decides whether this design works"
# Both instances claim the SAME platform_id under the SAME pipe name. Un-namespaced these are one
# row and the second insert is swallowed by the primary key; namespaced they are two independent
# deliveries. This is checked directly rather than inferred from a pipeline run, because it is the
# single assumption everything else rests on.
q "delete from public.sync_ledger where platform_id='_proof_collide';" >/dev/null
q "insert into public.sync_ledger (source,platform_id,status,delivered_at)
   values ('$A_INST/$PIPE','_proof_collide','delivered',now()),
          ('$B_INST/$PIPE','_proof_collide','delivered',now());" >/dev/null 2>&1
BOTH=$(q "select count(*) from public.sync_ledger where platform_id='_proof_collide';")
check "same id + same pipe name in both instances" "$BOTH" "2"
check "  ...and A's row is A's"  "$(q "select count(*) from public.sync_ledger where platform_id='_proof_collide' and source='$A_INST/$PIPE';")" "1"
check "  ...and B's row is B's"  "$(q "select count(*) from public.sync_ledger where platform_id='_proof_collide' and source='$B_INST/$PIPE';")" "1"

# and the un-namespaced form must NOT be what the engine writes any more
check "no un-namespaced ledger rows remain" \
  "$(q "select count(*) from public.sync_ledger where source not like '%/%';")" "0"

# ─────────────────────────────────────────────────────────────────────────────
echo
echo "── 4. one scanner pass must FAN OUT to both instances"
# `Registry Req` reads with instance:'*' and `Build Units` iterates every row it gets back. If it
# ever regresses to .first(), one instance is reconciled and the other silently is not — which is
# why this asserts on B's units existing, not merely on the run succeeding.
SEEN=$(q "select count(distinct instance) from public.settings where key='sync_registry';")
check "registries visible to the scanner" "$SEEN" "2"

if [ -n "${N8N:-}" ]; then
  q "insert into public.drive_files (id,name,folder) values
       ('_proof_b_doc','proof_b.pdf','_proof_b_src')
     on conflict (id) do update set folder='_proof_b_src';" >/dev/null 2>&1
  echo "   seeded B a document in _proof_b_src; triggering one Main pass…"
  docker exec "$N8N" sh -lc "curl -s -m 90 -X POST http://localhost:5678/webhook/indox-manage \
     -H 'Content-Type: application/json' -d '{\"INLINE_ACTION\":\"SCAN\"}' >/dev/null" 2>/dev/null || true
  sleep 8
  A_LEDGER=$(q "select count(*) from public.sync_ledger where source='$A_INST/$PIPE';")
  B_LEDGER=$(q "select count(*) from public.sync_ledger where source='$B_INST/$PIPE';")
  echo "   after the pass: A ledger rows=$A_LEDGER   B ledger rows=$B_LEDGER"
  check "A's ledger rows stayed under A's namespace" \
    "$(q "select count(*) from public.sync_ledger where source='$A_INST/$PIPE' and platform_id='_proof_b_doc';")" "0"
else
  echo "   (n8n container not found — skipping the live scanner pass)"
fi

# ─────────────────────────────────────────────────────────────────────────────
echo
echo "── 5. documents stay table-per-instance"
check "B has its own target table" \
  "$(q "select count(*) from information_schema.tables where table_schema='public' and table_name='$B_TABLE';")" "1"
check "B's table did not inherit A's rows" \
  "$(q "select count(*) from public.$B_TABLE;")" "0"
check "A's table is untouched by any of this" \
  "$(q "select count(*) from public.incoming_documents where \"CONNECTION\"='proof-b-conn';")" "0"

echo
echo "════════ $pass passed, $fail failed ════════"
[ "$fail" -eq 0 ] || exit 1
