#!/usr/bin/env python3
"""instances — more than one copy of an app on one office: its instances («מופעים», DGO-1920).

    python3 platform/manager/instances.py list [--json]
    python3 platform/manager/instances.py add <app> [--key <key>] [--title-he <t>] [--title-en <t>] [--by <who>]
    python3 platform/manager/instances.py remove <instance-id> [--by <who>]
    python3 platform/manager/instances.py sync [--check]

WHY. The owner, 2026-11-17: «dgo as a operating system supports multi instance of every app so i can runs
2-3 claude desktops on hp every one with diffrent account and same for other applications».

THE MODEL (the research is on DGO-1920; ai/context/app-instances.md says it in full):
  * An app is a TEMPLATE. Its first copy keeps the bare id (`bina-claude`), so nothing that exists moves.
    Every further copy is an INSTANCE with an id of its own: `<app>-<key>` (`bina-claude-2`). The app id and
    the key are kept as two fields (`of`, `key`) and never parsed back out of the id — app ids hold `-`.
  * The DECLARATION is the office's desired state, platform.state.yaml:
        app_instances:
          bina-claude-2: { of: bina-claude, key: "2", title: { he: …, en: … } }
    and, like every app, a disposition under `apps:` (`bina-claude-2: { state: enabled, by: user }`).
  * The instance's FOLDER, instances/<id>/, is GENERATED from that declaration and the template, and is
    never edited: app.json (the template's, every name derived) and docker-compose.yml, a full copy of the
    template's services with what makes a copy a copy changed — the names, the data, the ports — and every
    relative path pointed back at the template's folder. Every render writes it again (reconcile.py
    sync_instances), so a change to the template (an image, an env var, a limit) reaches every instance at
    the next compile. Not `extends`: replacing what it inherits needs compose's `!override` tag, which the
    office's YAML readers refuse (the compiler's did, on the first instance).
  * Both compilers read instances/ as one more catalog root (layer 3). Nothing of the render is written
    twice: to the compiler an instance is an app like any other — its routes, its tile, its sign-in
    client, its validation, its collisions (two hosts, two tiles, two slugs) are the compiler's.
  * ONE NAME HELPER (`derive_name`), as Helm's `fullname`: a name that starts with the template's id has
    that prefix replaced by the instance's (`bina-claude-desktop` → `bina-claude-2-desktop`); any other
    gets the instance id in front. Volumes are `<volume>_<key>`; routed hosts are `<host>-<key>`.
  * The app is told who it is, as snap tells SNAP_INSTANCE_KEY: DGO_INSTANCE_ID, DGO_INSTANCE_OF and
    DGO_INSTANCE_KEY in every one of its containers, and in the environment of its hooks (bbox).
  * An instance never changes another app: no `contributes` (env pushed into a neighbour would recreate
    it), no `agent` brief (the template's says it), and no published host port of its own choosing — its
    container ports are published on a port the engine picks (`docker port` says which).
  * Removing an instance removes its declaration, its folder and its containers' place in the office; its
    DATA (the named volumes) is kept, as `apps disable` keeps an app's. Deleting data is never this tool's.

WHICH APPS. Layer 3 apps, unless the manifest says `"multi_instance": false`; a layer 1–2 app (the
office's chassis: the edge, the database, the sign-in) only when it says `"multi_instance": true`. Refused,
with the reason: an app with no compose file, one whose compose writes its own traefik labels (the router
names would collide), one with n8n blueprints (their workflow ids are fixed), configs/secrets, an instance
of an instance.
"""
