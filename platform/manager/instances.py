class Refused(Exception):
    """A request this tool will not carry out, with the reason the caller shows."""


# ── the declaration ─────────────────────────────────────────────────────────────────────────────
def declared(state: dict | None = None) -> dict:
    """{instance id: {of, key, title?, env?}} as platform.state.yaml declares them (malformed rows dropped:
    `validate_block` is what says why)."""
    st = state if state is not None else _state()
    block = st.get(BLOCK) if isinstance(st, dict) else None
    if not isinstance(block, dict):
        return {}
    return {k: v for k, v in block.items() if isinstance(k, str) and isinstance(v, dict)}


def _state() -> dict:
    try:
        return yaml.safe_load(STATE.read_text(encoding="utf-8")) or {}
    except FileNotFoundError:
        return {}


def validate_block(block: dict, cat: dict) -> list[str]:
    """Why each declared instance cannot be generated — empty when every one can."""
    errs = []
    for iid, d in sorted(block.items()):
        of, key = d.get("of"), str(d.get("key", ""))
        if not ID_RE.match(iid):
            errs.append(f"{iid}: not an app id (a-z, 0-9 and '-', at most 31)")
            continue
        if of not in cat:
            errs.append(f"{iid}: its app {of!r} is not in this office's catalog")
            continue
        if not KEY_RE.match(key):
            errs.append(f"{iid}: key {key!r} is not a key (a-z, 0-9 and '-', at most 16)")
            continue
        if iid != instance_id(of, key):
            errs.append(f"{iid}: the id of instance {key!r} of {of} is {instance_id(of, key)}")
            continue
        why = refusal(cat[of])
        if why:
            errs.append(f"{iid}: {why}")
    return errs


def instance_id(of: str, key: str) -> str:
    return f"{of}-{key}"


def cannot_have_instances(m: dict) -> str:
    """'' when the app may have instances, else why not (the manifest alone answers)."""
    aid = m.get("id")
    if m.get("instance_of"):
        return f"{aid} is itself an instance (of {m['instance_of']}); add an instance of {m['instance_of']}"
    say = m.get("multi_instance")
    if say is False:
        return f"{aid} says it runs once per office (app.json multi_instance: false)"
    if say is not True and m.get("layer") != 3:
        return (f"{aid} is layer {m.get('layer')}, the office's own chassis, which runs once per office "
                f"(an app of layers 1–2 has instances only when its app.json says multi_instance: true)")
    if m.get("system") or m.get("core"):
        return f"{aid} is a system app of the office, which runs once"
    if not m.get("compose"):
        return f"{aid} owns no container (no compose file): there is nothing to run twice"
    if m.get("blueprints"):
        return f"{aid} carries n8n workflows, whose ids are fixed: a second copy would overwrite the first's"
    data = m.get("data") if isinstance(m.get("data"), dict) else {}
    shared = [k for k in ("paths", "sql", "kv") if data.get(k)]
    if shared:
        return (f"{aid} keeps data outside its own volumes (app.json data.{', data.'.join(shared)}), which a copy "
                f"would share with the first: only an app whose data is all in named volumes is copied")
    folders = [v for v in data.get("volumes") or [] if not (isinstance(v, str) and VOLUME_RE.match(v))]
    if folders:
        return (f"{aid} keeps data in a host folder (app.json data.volumes: {folders[0]}), which a copy would share "
                f"with the first: only an app whose data is all in named volumes is copied")
    return ""


#: A named volume's name, as compose takes it — anything else in `data.volumes` is a host folder.
VOLUME_RE = re.compile(r"^[a-zA-Z0-9][a-zA-Z0-9_.-]*\Z")
#: The hooks the office runs BY ITSELF around an app's life (bbox run, the apps screen). Written for one copy, they
#: act on the first one's data when run for a copy — an `uninstall` would clear the original's.
LIFECYCLE_HOOKS = ("prepare", "onboard", "uninstall", "backup", "restore", "migrate", "update", "self-update")
#: Mount sources set in .env that apps share on purpose: the office's checkout, the engine's socket, the vault.
SHARED_SOURCES = {"BBOX_REPO_HOST", "BBOX_DOCKER_SOCK", "OBSIDIAN_VAULT_HOST"}
#: …of which these make an app a hand on the OFFICE ITSELF (its files, every container): a second copy is a second
#: controller of the same thing, so it is the app's own decision (`multi_instance: true`), never the default.
OFFICE_HANDS = {"BBOX_REPO_HOST", "BBOX_DOCKER_SOCK"}
_FILE_WHY = {}      # app dir -> (stamp, monotonic time, why-or-"")


def refusal(m: dict) -> str:
    """'' when a copy of this app can be generated AND run apart from the first, else why not. The manifest's word
    (cannot_have_instances), then what only its files say:
      * its compose: its own traefik routers, configs, links… (derive_compose refuses them);
    and, unless the app says `"multi_instance": true` — its author's word that its code reads DGO_INSTANCE_ID —
      * a lifecycle hook (LIFECYCLE_HOOKS): the office runs it by itself, and for a copy it would act on the first;
      * a mount whose source .env chooses (`${VAR…}`, other than SHARED_SOURCES): a copy would mount the same one;
      * a file of the app that names one of its services as an address (a Caddyfile's `ollama-engine:11434`): a
        copy would talk to the first copy's service.
    The files are read again when the compose file changes, or after a minute (a screen asks every 5 s)."""
    why = cannot_have_instances(m)
    if why or not m.get("_dir"):
        return why
    d = pathlib.Path(m["_dir"])
    path = d / m["compose"]
    try:
        st = path.stat()
        stamp = (st.st_mtime_ns, st.st_size, m.get("multi_instance"))
    except OSError:
        return f"{m.get('id')}'s compose file is not there"
    hit = _FILE_WHY.get(str(d))
    if hit and hit[0] == stamp and time.monotonic() - hit[1] < 60:
        return hit[2]
    try:
        compose = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        derive_compose(m, compose, d, ROOT / f"{m['id']}-x", f"{m['id']}-x", "x", None)
        why = "" if m.get("multi_instance") is True else _not_self_contained(m, compose, d)
    except Refused as e:
        why = str(e)
    except (OSError, yaml.YAMLError) as e:
        why = f"{m.get('id')}'s compose file cannot be read: {e}"
    _FILE_WHY[str(d)] = (stamp, time.monotonic(), why)
    return why


def _not_self_contained(m: dict, compose: dict, d: pathlib.Path) -> str:
    aid, say = m.get("id"), "a copy needs the app to say \"multi_instance\": true, once its code reads DGO_INSTANCE_ID"
    hooks = [h for h in LIFECYCLE_HOOKS for e in ("", ".sh", ".py", ".mjs") if (d / "hooks" / f"{h}{e}").is_file()]
    if hooks:
        return f"{aid} has lifecycle hooks (hooks/{hooks[0]}) written for one copy, which would act on the first; {say}"
    services = compose.get("services") or {}
    own = own_volumes(m, compose)
    for svc, spec in services.items():
        spec = spec or {}
        if str(spec.get("network_mode") or "") == "host":
            return f"{aid}'s {svc} runs on the host's network, where a copy's ports would be the first's; {say}"
        for v in spec.get("volumes") or []:
            src = v.get("source") if isinstance(v, dict) else _split_colon(str(v))[0]
            var = re.match(r"\$\{(\w+)", str(src or ""))
            if var and var.group(1) not in SHARED_SOURCES:
                return f"{aid}'s mount on {svc} comes from .env (${{{var.group(1)}}}), which a copy would share; {say}"
            if (var and var.group(1) in OFFICE_HANDS) or str(src or "").endswith("docker.sock"):
                return (f"{aid}'s {svc} mounts the office itself (its checkout or the engine), so a copy would be a "
                        f"second hand on the same office; {say}")
            # a host folder (./state, /srv/x) the app may WRITE: both copies would write it — read-only config is fine
            if isinstance(v, dict):
                bind = v.get("type") == "bind"
                ro = bool(v.get("read_only"))
            else:
                parts = _split_colon(str(v))
                bind = len(parts) >= 2 and parts[0] not in own and parts[0].startswith(("/", ".", "~", "$"))
                ro = len(parts) >= 3 and "ro" in parts[2].split(",")
            if bind and not ro and not (var and var.group(1) in SHARED_SOURCES):
                return f"{aid}'s {svc} writes a host folder ({src}), which a copy would share; {say}"
    names = "|".join(re.escape(s) for s in services)
    # an ADDRESS: `<scheme>://svc` (a URL) or `svc:<port>` — never a path segment (/opt/bina-claude/), never another
    # host that begins with the name (//slack.com, //api.example.com), never an id that only looks like one
    # (an iCalendar `PRODID:-//examplech-services//…`)
    addr = re.compile(rf"\b[a-z][a-z0-9+.-]*://({names})(?![\w.-])|(?<![\w/.-])({names}):\d+")
    skip = {m.get("compose"), "app.json"}
    for f in sorted(d.rglob("*")):
        rel = f.relative_to(d)
        if (not f.is_file() or rel.parts[0] in ("hooks", "tests", "test", "node_modules", "__pycache__", ".git")
                or str(rel) in skip or f.suffix in (".md", ".png", ".jpg", ".svg", ".ico", ".woff2")
                or f.name.startswith("test_") or f.stat().st_size > 200_000):
            continue
        try:
            hit = addr.search(f.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError):
            continue
        if hit:
            svc = hit.group(1) or hit.group(2)
            return f"{aid}'s {rel} addresses its own service {svc} by name, which a copy would share; {say}"
    return ""


# ── one name helper ─────────────────────────────────────────────────────────────────────────────
def derive_name(name: str, of: str, iid: str) -> str:
    """The instance's name for a name of its template's (a service, a container, a router, a tile)."""
    if name == of or name.startswith(of + "-") or name.startswith(of + "_"):
        return iid + name[len(of):]
    return f"{iid}-{name}"


def derive_volume(vol: str, key: str) -> str:
    return f"{vol}_{key.replace('-', '_')}"


def env_suffix(key: str) -> str:
    return re.sub(r"[^A-Z0-9]", "_", key.upper())


# ── the manifest ────────────────────────────────────────────────────────────────────────────────
def _rehost(text, hosts: dict):
    """A URL's host renamed when it is one of the template's services (`http://bina-claude:3091/x`)."""
    if not isinstance(text, str):
        return text
    return re.sub(r"(//)([a-z0-9][a-z0-9_.-]*)(?=[:/]|$)", lambda m: m.group(1) + hosts.get(m.group(2), m.group(2)),
                  text)


def derive_manifest(tpl: dict, iid: str, key: str, title: dict | None, services: list[str]) -> dict:
    of = tpl["id"]
    hosts = {s: derive_name(s, of, iid) for s in services}
    m = {k: copy.deepcopy(v) for k, v in tpl.items() if not k.startswith("_")}
    for drop in ("contributes", "agent", "multi_instance"):
        m.pop(drop, None)
    m["id"] = iid
    m["instance_of"] = of
    m["instance_key"] = key
    t = tpl.get("title") or {}
    title = title or {}
    m["title"] = {"he": title.get("he") or f"{t.get('he', of)} {key}",
                  "en": title.get("en") or f"{t.get('en', of)} {key}"}
    m["compose"] = "docker-compose.yml"
    if m.get("agent_api_service") in hosts:
        m["agent_api_service"] = hosts[m["agent_api_service"]]
    for c in m.get("capabilities") or []:
        if isinstance(c, dict) and "endpoint" in c:
            c["endpoint"] = _rehost(c["endpoint"], hosts)
    for o in m.get("ops") or []:
        if isinstance(o, dict) and "endpoint" in o:
            o["endpoint"] = _rehost(o["endpoint"], hosts)
    probe = (m.get("health") or {}).get("probe")
    if isinstance(probe, dict) and "http" in probe:
        probe["http"] = _rehost(probe["http"], hosts)
    data = m.get("data")
    if isinstance(data, dict):
        if isinstance(data.get("volumes"), list):
            data["volumes"] = [derive_volume(v, key) if isinstance(v, str) else v for v in data["volumes"]]
        if isinstance(data.get("writers"), list):
            data["writers"] = [derive_name(w, of, iid) if isinstance(w, str) else w for w in data["writers"]]
    cli = m.get("cli")
    if isinstance(cli, dict) and isinstance(cli.get("alias"), str):
        cli["alias"] = f"{cli['alias']}-{key}"
    sfx = env_suffix(key)
    for r in m.get("routing") or []:
        if not isinstance(r, dict):
            continue
        if isinstance(r.get("host"), str):
            r["host"] = f"{r['host']}-{key}"
        if r.get("service") in hosts:
            r["service"] = hosts[r["service"]]
        if isinstance(r.get("name"), str):
            r["name"] = derive_name(r["name"], of, iid)
        if isinstance(r.get("url_env"), str):
            r["url_env"] = f"{r['url_env']}_{sfx}"
        mod = r.get("module")
        if isinstance(mod, dict):
            for k in ("id", "alias"):
                if isinstance(mod.get(k), str):
                    mod[k] = derive_name(mod[k], of, iid)
            mod["name"] = m["title"]["he"]
            if "url" in mod:
                mod["url"] = _rehost(mod["url"], hosts)
            if isinstance(mod.get("url_env"), str):
                mod["url_env"] = f"{mod['url_env']}_{sfx}"
        sso = r.get("sso")
        if isinstance(sso, dict):
            sso["slug"] = derive_name(sso.get("slug") or of, of, iid)
            sso["display_name"] = m["title"]["en"]
            if isinstance(sso.get("default_host"), str):
                head, _, rest = sso["default_host"].partition(".")
                sso["default_host"] = f"{head}-{key}.{rest}" if rest else f"{head}-{key}"
            if isinstance(sso.get("base_url_env"), str):
                sso["base_url_env"] = f"{sso['base_url_env']}_{sfx}"
    return m


# ── the compose file ────────────────────────────────────────────────────────────────────────────
# A FULL COPY of the template's services, never `extends`: a copy must REPLACE what it inherits (its published
# ports, its dependencies), which only compose's `!override`/`!reset` tags can say, and every YAML reader of the
# office (the compiler first: render refused the first instance, 2026-11-17) reads compose files as plain YAML.
# The copy is written again at every render (reconcile.sync_instances), so a change to the template reaches
# every instance at the next compile. instances/<id>/ sits at the depth of apps/<id>/, and every relative path
# of the template's is rewritten from the instance's folder (`./adapter` → `../../apps/bina-claude/adapter`).
def _relocate(p, src: pathlib.Path, dst: pathlib.Path):
    """A path of the template's compose as the instance's must write it — and a `${VAR:-<path>}` default too."""
    if not isinstance(p, str):
        return p
    m = re.fullmatch(r"(\$\{\w+:?-)(\.{1,2}(?:/[^}]*)?)(\})", p)
    if m:
        return m.group(1) + _relocate(m.group(2), src, dst) + m.group(3)
    if p == "." or p.startswith(("./", "../")) or p == "..":
        return os.path.relpath(os.path.normpath(src / p), dst).replace(os.sep, "/")
    return p


def _split_colon(text: str) -> list[str]:
    """`a:b:c` split on the colons that are not inside a `${…}` (whose `:-` is a default, not a field)."""
    parts, cur, depth, i = [], "", 0, 0
    while i < len(text):
        ch = text[i]
        if text.startswith("${", i):
            depth += 1
            cur += "${"
            i += 2
            continue
        if ch == "}" and depth:
            depth -= 1
        if ch == ":" and not depth:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
        i += 1
    parts.append(cur)
    return parts


def _ephemeral(port):
    """The same container port, published on a host port the engine picks (and the same bind address)."""
    if isinstance(port, dict):
        p = {k: v for k, v in port.items() if k != "published"}
        return p
    p = _split_colon(str(port))
    if len(p) == 3:
        return f"{p[0]}::{p[2]}"
    return p[-1]


def own_volumes(tpl: dict, compose: dict) -> set:
    """The template's own named volumes: what its manifest declares as its data, plus any top-level volume
    of its compose named after it (`bina_claude_*`). Every other volume it mounts is a neighbour's, shared."""
    own = {v for v in (tpl.get("data") or {}).get("volumes") or [] if isinstance(v, str) and VOLUME_RE.match(v)}
    prefix = tpl["id"].replace("-", "_") + "_"
    own |= {v for v in (compose.get("volumes") or {}) if isinstance(v, str) and (v.startswith(prefix) or v == prefix[:-1])}
    return own


def _own_source(src, own: set, key: str):
    """A mount's source renamed when it is one of the app's own volumes — written plainly, or as the default of
    a `${VAR:-<volume>}` (an app that says multi_instance: true and still lets .env move its data): the VARIABLE
    is the copy's own too (`${VAR_2:-vol_2}`), as `url_env` is — what .env sets for the first copy is never the
    copy's folder."""
    if src in own:
        return derive_volume(src, key)
    m = re.fullmatch(r"\$\{(\w+)(:?-)([^}]+)\}", str(src or ""))
    if m and m.group(3) in own:
        return f"${{{m.group(1)}_{env_suffix(key)}{m.group(2)}{derive_volume(m.group(3), key)}}}"
    return None


def derive_compose(tpl: dict, compose: dict, src: pathlib.Path, dst: pathlib.Path, iid: str, key: str,
                   env: dict | None) -> dict:
    of = tpl["id"]
    if compose.get("configs") or compose.get("secrets"):
        raise Refused(f"{of}'s compose declares configs/secrets, which are not copied per instance")
    services = compose.get("services") or {}
    if not services:
        raise Refused(f"{of}'s compose declares no service")
    names = {s: derive_name(s, of, iid) for s in services}
    own = own_volumes(tpl, compose)
    out_services = {}
    for svc, spec in services.items():
        new = copy.deepcopy(spec or {})
        labels = new.get("labels") or {}
        lab_keys = labels.keys() if isinstance(labels, dict) else [str(x).split("=", 1)[0] for x in labels]
        if any(str(k).startswith("traefik.http.") or str(k).startswith("traefik.tcp.") for k in lab_keys):
            raise Refused(f"{of}'s service {svc} writes its own traefik routers, whose names would collide "
                          f"in a copy (the compiler's routing[] is what an instance can carry)")
        for k in ("volumes_from", "links", "extends"):
            if new.get(k):
                raise Refused(f"{of}'s service {svc} uses {k}, which a copy cannot follow")
        cn = new.get("container_name")
        if isinstance(cn, str):
            new["container_name"] = names[svc] + cn[len(svc):] if cn.startswith(svc) else f"{cn}-{key}"
        hn = new.get("hostname")
        if isinstance(hn, str) and (hn == svc or hn.startswith(svc + "-")):
            new["hostname"] = names[svc] + hn[len(svc):]
        elif isinstance(hn, str):
            new["hostname"] = f"{hn}-{key}"   # a machine name the app shows (hp-dgo → hp-dgo-2): never the first copy's
        nm = new.get("network_mode")
        if isinstance(nm, str) and nm.startswith("service:") and nm[8:] in names:
            new["network_mode"] = "service:" + names[nm[8:]]
        # the build and every relative path, from the instance's folder
        b = new.get("build")
        if isinstance(b, str):
            new["build"] = _relocate(b, src, dst)
        elif isinstance(b, dict) and "context" in b:
            b["context"] = _relocate(b["context"], src, dst)
        ef = new.get("env_file")
        if isinstance(ef, (str, list)):
            new["env_file"] = [(_relocate(x, src, dst) if isinstance(x, str) else
                                {**x, "path": _relocate(x.get("path"), src, dst)}) for x in ([ef] if isinstance(ef, str) else ef)]
        # who it is, and the addresses of its own services renamed
        tenv = new.get("environment") or {}
        items = list(tenv.items()) if isinstance(tenv, dict) else [
            (x.split("=", 1)[0], x.split("=", 1)[1] if "=" in x else None) for x in tenv]
        e = {k: (_rehost(v, names) if isinstance(v, str) else v) for k, v in items}
        e.update({"DGO_INSTANCE_ID": iid, "DGO_INSTANCE_OF": of, "DGO_INSTANCE_KEY": key})
        e.update({k: str(v) for k, v in (env or {}).items()})
        new["environment"] = e
        # its own volumes renamed, the shared ones left shared, a bind relocated
        mounts = []
        for v in new.get("volumes") or []:
            if isinstance(v, dict):
                v = dict(v)
                if v.get("type", "volume") == "volume" and _own_source(v.get("source"), own, key):
                    v["source"] = _own_source(v["source"], own, key)
                elif v.get("type") == "bind":
                    v["source"] = _relocate(v.get("source"), src, dst)
                mounts.append(v)
                continue
            p = _split_colon(str(v))
            if _own_source(p[0], own, key):
                p[0] = _own_source(p[0], own, key)
            elif len(p) >= 2:
                p[0] = _relocate(p[0], src, dst)
            mounts.append(":".join(p))
        if mounts:
            new["volumes"] = mounts
        if new.get("ports"):
            new["ports"] = [_ephemeral(p) for p in new["ports"]]
        dep = new.get("depends_on")
        if dep:
            dmap = dep if isinstance(dep, dict) else {d: {"condition": "service_started"} for d in dep}
            new["depends_on"] = {names.get(k, k): v for k, v in dmap.items()}
        out_services[names[svc]] = new
    vols = {}
    for name, spec in (compose.get("volumes") or {}).items():
        if name in own:
            spec = copy.deepcopy(spec) if isinstance(spec, dict) else None
            if isinstance(spec, dict) and isinstance(spec.get("name"), str):
                spec["name"] = derive_volume(spec["name"], key)
            vols[derive_volume(name, key)] = spec
        else:
            vols[name] = copy.deepcopy(spec)
    for n in sorted(own):
        vols.setdefault(derive_volume(n, key), None)
    doc = {"services": out_services}
    if vols:
        doc["volumes"] = vols
    if compose.get("networks"):
        doc["networks"] = copy.deepcopy(compose["networks"])
    return doc


# ── generation ──────────────────────────────────────────────────────────────────────────────────
def render_instance(iid: str, decl: dict, cat: dict) -> dict:
    """{relative file name: text} of instances/<iid>/ — or Refused."""
    of, key = decl["of"], str(decl["key"])
    tpl = cat[of]
    why = refusal(tpl)
    if why:
        raise Refused(why)
    src = tpl["_dir"] / tpl["compose"]
    try:
        compose = yaml.safe_load(src.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as e:
        raise Refused(f"{of}'s compose file cannot be read: {e}") from e
    doc = derive_compose(tpl, compose, src.parent, ROOT / iid, iid, key, decl.get("env"))
    man = derive_manifest(tpl, iid, key, decl.get("title"), list((compose.get("services") or {}).keys()))
    head = (f"# instance {key!r} of {of} — {man['title']['en']}\n" + HEADER)
    return {
        "app.json": json.dumps(man, ensure_ascii=False, indent=2) + "\n",
        "docker-compose.yml": head + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True,
                                                   default_flow_style=False, width=1000),
        MARK: json.dumps({"of": of, "key": key}, ensure_ascii=False) + "\n",
    }


def _write(folder: pathlib.Path, name: str, text: str) -> None:
    """One generated file, replaced whole — and, written by root into a checkout someone else owns (app-management's
    container compiles as root), handed to the checkout's owner, as reconcile.hand_back does for .generated/ (DGO-121):
    the owner's next `bbox apps instance sync` must be able to write it again."""
    made = not folder.exists()
    folder.mkdir(parents=True, exist_ok=True)
    tmp = folder / f".{name}.tmp"
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, folder / name)
    if hasattr(os, "geteuid") and os.geteuid() == 0:
        try:
            owner = os.stat(REPO)
            if owner.st_uid != 0:
                for p in ([ROOT, folder] if made else []) + [folder / name]:
                    os.lchown(p, owner.st_uid, owner.st_gid)
        except OSError:
            pass


def _template_catalog() -> dict:
    """The catalog the templates come from: apps/ and platform-base/ only, read without instances/ — a broken
    manifest there (a write cut short) must never stop the sync that writes it again. load_catalog's own rules
    (id = folder, the layer is the folder's) stand for the two roots it reads."""
    roots = {r: layers for r, layers in reconcile.CATALOG_ROOTS.items() if r != reconcile.INSTANCES}
    keep = reconcile.CATALOG_ROOTS
    try:
        reconcile.CATALOG_ROOTS = roots
        return reconcile.load_catalog()
    finally:
        reconcile.CATALOG_ROOTS = keep


def sync(check: bool = False, quiet: bool = False) -> tuple[list[str], list[str]]:
    """instances/ := what the state declares. Returns (changed paths, errors). `check` writes nothing.

    A folder of instances/ that carries the mark and is no longer declared is removed (its data is not:
    that is in the engine's volumes). A folder without the mark is never touched. Nothing at all is done from a
    file that is not a state file (no `schema_version: 1`): a truncated read declares no instance, and every
    folder would go — the compiler refuses that file right after, and so does this."""
    # Under the state file's lock: `add` writes the folder, then the rows, under it — a render's sync between the
    # two would read no row and remove the folder `add` just wrote.
    with reconcile._state_lock():
        changed, errs = _sync(check)
    if not quiet:
        for c in changed:
            print(f"  {'would write' if check else 'wrote'}  {c}")
        for e in errs:
            print(f"  REFUSED  {e}", file=sys.stderr)
    return changed, errs


def _sync(check: bool) -> tuple[list[str], list[str]]:
    st = _state()
    if not isinstance(st, dict) or st.get("schema_version") != 1:
        return [], [f"{STATE.name} is not a state file (no schema_version: 1) — no instance was synced"]
    cat = _template_catalog()
    block = declared(st)
    errs = validate_block(block, cat)
    bad = {e.split(":", 1)[0] for e in errs}
    changed = []
    for iid, d in sorted(block.items()):
        if iid in bad:
            continue
        try:                                   # one instance's trouble is said, and the others and the render go on
            files = render_instance(iid, d, cat)
        except Refused as e:
            errs.append(f"{iid}: {e}")
            continue
        except Exception as e:                 # noqa: BLE001
            errs.append(f"{iid}: not generated ({type(e).__name__}: {e})")
            continue
        folder = ROOT / iid
        for name, text in files.items():
            p = folder / name
            try:
                if p.read_text(encoding="utf-8") == text:
                    continue
            except OSError:
                pass
            changed.append(str(p.relative_to(REPO)))
            if not check:
                try:
                    _write(folder, name, text)
                except OSError as e:           # said, and the render goes on with the folder as it is
                    errs.append(f"{iid}: {p.relative_to(REPO)} cannot be written ({e.strerror or e})")
    if ROOT.is_dir():
        for folder in sorted(ROOT.iterdir()):
            if not (folder.is_dir() and (folder / MARK).exists()):
                continue
            row = block.get(folder.name)
            # gone from the state — or its template is gone from the office, so its copy points at nothing
            if row is None or row.get("of") not in cat:
                changed.append(str(folder.relative_to(REPO)) + "/ (removed)")
                if not check:
                    try:
                        shutil.rmtree(folder)
                    except OSError as e:
                        errs.append(f"{folder.name}: its folder cannot be removed ({e.strerror or e})")
    return changed, errs


# ── the state file's block (text surgery, the compiler's way: every comment of the file stays) ─────
_BLOCK_NOTE = ("# ── app instances («מופעים», DGO-1920): further copies of an app, each with its own containers,\n"
               "# data, address, tile and sign-in. Written by `bbox apps instance add|remove` (and the apps\n"
               "# screen's «מופע נוסף»); instances/<id>/ is generated from each row. ai/context/app-instances.md.\n")


@reconcile._under_state_lock
def write_block(block: dict) -> bool:
    """THE writer of `app_instances:` in platform.state.yaml: cut out and re-appended, nothing else moved."""
    text = STATE.read_text(encoding="utf-8")
    if declared(yaml.safe_load(text) or {}) == block:
        return False
    # Two things are cut: the note (from its first line to the block's key, comments only) and the block (its key
    # and its indented rows). Anything else — a block written after this one, with a comment header of its own
    # (`office:`, `remote:`) — is kept, so the scan stops at the first line that is neither.
    out, where = [], None
    for ln in text.splitlines(keepends=True):
        if ln.startswith(_BLOCK_NOTE.splitlines()[0][:40]):
            where = "note"
            continue
        if re.match(rf"^{BLOCK}:\s*(#.*)?$", ln):
            where = "rows"
            continue
        if where == "note" and ln.startswith("#"):
            continue
        if where == "rows" and ln[:1].isspace() and ln.strip():
            continue
        where = None
        out.append(ln)
    new = "".join(out).rstrip("\n") + "\n"
    if block:
        # BLOCK style, never `  <id>: { … }` on one line: that is the shape of an `apps:` row, and the
        # compiler's disposition reader and writer find a row by `^\s+<id>:\s*{` anywhere in the file.
        new += "\n" + _BLOCK_NOTE + yaml.safe_dump({BLOCK: dict(sorted(block.items()))}, allow_unicode=True,
                                                   sort_keys=False, default_flow_style=False, width=1000)
    reconcile._write_state(new)
    return True


def _title(he: str | None, en: str | None) -> dict:
    t = {}
    for lang, v in (("he", he), ("en", en)):
        if v:
            v = " ".join(str(v).split())
            if len(v) > TITLE_MAX or any(c in v for c in "{}[]\"\\"):
                raise Refused(f"title ({lang}) must be plain text of at most {TITLE_MAX} characters")
            t[lang] = v
    return t


def add(of: str, key: str | None = None, title_he: str | None = None, title_en: str | None = None,
        by: str = "user") -> str:
    """Declare and enable a new instance of `of`; returns its id. Generates its folder."""
    cat = reconcile.load_catalog()
    if of not in cat:
        raise Refused(f"no app {of!r} in this office's catalog")
    why = refusal(cat[of])
    if why:
        raise Refused(why)
    with reconcile._state_lock():
        block = declared()
        taken = set(cat) | set(block)
        if key is None:
            n = 2
            while instance_id(of, str(n)) in taken:
                n += 1
            key = str(n)
        key = str(key).strip().lower()
        if not KEY_RE.match(key):
            raise Refused(f"key {key!r} is not a key (a-z, 0-9 and '-', at most 16, not starting or ending with '-')")
        iid = instance_id(of, key)
        if not ID_RE.match(iid):
            raise Refused(f"{iid} is too long for an app id (at most 31) — choose a shorter key")
        if iid in taken:
            raise Refused(f"{iid} already exists in this office")
        row = {"of": of, "key": key}
        t = _title(title_he, title_en)
        if t:
            row["title"] = t
        row["added"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        row["by"] = by
        files = render_instance(iid, row, _template_catalog())   # refuses before anything is written
        _no_clash(iid, files, cat)
        _compose_accepts(of, iid, files, cat)
        folder = ROOT / iid
        for name, text in files.items():
            _write(folder, name, text)
        # the folder first (set_disposition reads its manifest's requires_host), then the `apps:` row, then
        # the declaration — a failure in between leaves a folder `sync` removes, never a row without a folder
        try:
            reconcile.set_disposition(iid, "enabled", by=by, create=True)
        except ValueError as e:
            shutil.rmtree(folder)
            raise Refused(str(e)) from e
        block[iid] = row
        write_block(block)
    return iid


def _no_clash(iid: str, files: dict, cat: dict) -> None:
    """Refused when a name the copy would take is already taken in this office: a service, a container, an app id,
    a routed host, a tile, a sign-in slug. A key can make one (`bina-claude --key desktop` → bina-claude-desktop,
    the FIRST copy's desktop service and container) — and a clash found by the compiler after the row is written
    leaves the office unable to compile until someone removes it."""
    doc = yaml.safe_load(files["docker-compose.yml"]) or {}
    man = json.loads(files["app.json"])
    mine = {("service", s) for s in doc.get("services") or {}}
    mine |= {("container", str(x.get("container_name"))) for x in (doc.get("services") or {}).values()
             if isinstance(x, dict) and x.get("container_name")}
    mine.add(("app", iid))
    for r in man.get("routing") or []:
        mine |= {("host", r.get("host")), ("tile", (r.get("module") or {}).get("id")),
                 ("alias", (r.get("module") or {}).get("alias")), ("slug", (r.get("sso") or {}).get("slug"))}
    taken = set()
    for aid, a in cat.items():
        taken.add(("app", aid))
        for r in a.get("routing") or []:
            taken |= {("host", r.get("host")), ("tile", (r.get("module") or {}).get("id")),
                      ("alias", (r.get("module") or {}).get("alias")), ("slug", (r.get("sso") or {}).get("slug"))}
        try:
            c = yaml.safe_load((a["_dir"] / a["compose"]).read_text(encoding="utf-8")) if a.get("compose") else {}
        except (OSError, yaml.YAMLError):
            continue
        for s, x in ((c or {}).get("services") or {}).items():
            taken.add(("service", s))
            if isinstance(x, dict) and x.get("container_name"):
                taken.add(("container", str(x["container_name"])))
    hit = sorted(n for n in mine & taken if n[1])
    if hit:
        kind, name = hit[0]
        raise Refused(f"{iid} would take the {kind} name {name!r}, which this office already has — choose another key")


def _compose_accepts(of: str, iid: str, files: dict, cat: dict) -> None:
    """Compose itself reads the template and the copy together, before anything is declared: what it refuses
    (a volume key that is not a name, an undefined volume, a clash) would otherwise refuse the WHOLE office's
    project at the next bring-up. Skipped where no compose answers (a CI runner without docker)."""
    if not shutil.which("docker"):
        return
    ROOT.mkdir(exist_ok=True)
    # instances/.check-…/ is at the depth of instances/<id>/, so the copy's relative paths (../../apps/<of>/…) resolve
    # to the template as they will; it carries no app.json and no mark, so neither the catalog nor sync sees it
    with tempfile.TemporaryDirectory(prefix=f".check-{iid}-", dir=str(ROOT)) as tmp:
        here = pathlib.Path(tmp)
        (here / "docker-compose.yml").write_text(files["docker-compose.yml"], encoding="utf-8")
        tpl = cat[of]["_dir"] / cat[of]["compose"]
        top = here / "check.yml"
        top.write_text(yaml.safe_dump({"name": "dgo-instance-check", "include": [str(tpl), str(here / "docker-compose.yml")]}),
                       encoding="utf-8")
        env = ["--env-file", str(REPO / ".env")] if (REPO / ".env").is_file() else []
        try:
            r = subprocess.run(["docker", "compose", "--project-directory", str(REPO), *env, "-f", str(top), "config", "-q"],
                               capture_output=True, text=True, timeout=60, cwd=str(REPO))
        except (OSError, subprocess.SubprocessError):
            return
        if r.returncode != 0 and "is not a docker command" not in (r.stderr or ""):
            why = (r.stderr or r.stdout or "").strip().splitlines()
            raise Refused(f"compose refuses {iid} beside {of}: {why[-1] if why else 'no reason given'}")


def remove(iid: str, by: str = "user") -> None:
    """Undeclare an instance: its row, its disposition, its folder. Its data (volumes) is kept."""
    with reconcile._state_lock():
        block = declared()
        if iid not in block:
            raise Refused(f"{iid} is not an instance of this office (`bbox apps instance list`)")
        block.pop(iid)
        write_block(block)
        _drop_disposition(iid)
        # under the lock, and a folder a render's sync already removed is not an error
        folder = ROOT / iid
        if (folder / MARK).exists():
            shutil.rmtree(folder, ignore_errors=True)


@reconcile._under_state_lock
def _drop_disposition(iid: str) -> None:
    """The instance's `apps:` row goes with it: an id with no app behind it is not left in the file."""
    txt = STATE.read_text(encoding="utf-8")
    new = re.sub(rf"^\s+{re.escape(iid)}:\s*\{{[^}}]*\}}[^\n]*\n", "", txt, count=1, flags=re.M)
    if new != txt:
        reconcile._write_state(new)


def rows(cat: dict | None = None) -> list[dict]:
    cat = cat if cat is not None else reconcile.load_catalog()
    st = _state()
    apps = st.get("apps") or {}
    out = []
    for iid, d in sorted(declared(st).items()):
        m = cat.get(iid) or {}
        out.append({"id": iid, "of": d.get("of"), "key": str(d.get("key", "")),
                    "title": (m.get("title") or d.get("title") or {}),
                    "state": reconcile.disposition(apps.get(iid)) if iid in apps else "undeclared",
                    "generated": (ROOT / iid / MARK).exists(), "added": d.get("added"), "by": d.get("by")})
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="instances", description="an app's further copies on this office")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("list")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("add")
    p.add_argument("app")
    p.add_argument("--key")
    p.add_argument("--title-he")
    p.add_argument("--title-en")
    p.add_argument("--by", default="cli")
    p = sub.add_parser("remove")
    p.add_argument("id")
    p.add_argument("--by", default="cli")
    p = sub.add_parser("sync")
    p.add_argument("--check", action="store_true", help="write nothing; exit 1 when a file would change")
    p.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "list":
            r = rows()
            if a.json:
                print(json.dumps(r, ensure_ascii=False, indent=2))
            elif not r:
                print("  no instances on this office (`bbox apps instance add <app>` adds one)")
            else:
                for x in r:
                    print(f"  {x['id']:<28} of {x['of']:<18} {x['state']:<9} {x['title'].get('en', '')}")
            return 0
        if a.cmd == "add":
            iid = add(a.app, a.key, a.title_he, a.title_en, by=a.by)
            print(f"  {iid}  added and enabled — instances/{iid}/ (its containers come up with `bbox run`)")
            return 0
        if a.cmd == "remove":
            remove(a.id, by=a.by)
            print(f"  {a.id}  removed — its data (volumes) is kept; `bbox apps disable` stops what still runs")
            return 0
        changed, errs = sync(check=a.check, quiet=a.quiet)
        if a.check:
            return 1 if (changed or errs) else 0
        return 1 if errs else 0
    except Refused as e:
        print(f"instances: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
