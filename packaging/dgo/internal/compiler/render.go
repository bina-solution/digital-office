// ── `render`: the office's configuration, compiled from the catalog and the state ─────────────────
//
// reconcile.py's render(cat, order, state), file for file and in its order, because the order is part
// of the answer: a refusal half way (SERVE PLAN REFUSED, a passthrough without its alias, a blueprint
// whose identities collide) leaves exactly the files written before it, as Python leaves them. What it
// writes: .env's derived slug (sync_identity), an archived generation of the last render, and under
// .generated/ compose.yml and its overlays (routing, connections, remote), glitchtip's projects, the
// registries the base apps mount, the agent's context and resolved.json — plus the two files it writes
// into apps' own config directories, traefik's zz-serve.yaml and authentik's zz-generated-apps.yaml.
// Every file is written by write(): unchanged bytes are not rewritten, because something watches each.

// exit is where reconcile.py stops with a message (sys.exit / raise SystemExit): the message on stderr
// as Python prints it, and exit 1 — a refusal, worded for the operator, not a crash.
type exit struct{ msg string }

func (e *exit) Error() string { return e.msg }

// RenderCmd is `render [--json]`: main()'s path for it — the catalog, the state, validate, resolve
// (its diagnostics on stdout, or on stderr with --json; a hard one is RESOLVE FAILED), render, and the
// two lines that say what was rendered and which -f files are now the stack.
func RenderCmd(repo string, args []string, stdout, stderr io.Writer) int {
	a, code, done := parseArgs("render", args, stdout, stderr)
	if done {
		return code
	}
	cat, st, _, code := loadAndValidate(repo, stdout, stderr)
	if code != 0 {
		return code
	}
	order, diags, err := Resolve(repo, cat, st, nil)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	diagOut := stdout
	if a.JSON { // --json makes stdout a document, so every note moves to stderr
		diagOut = stderr
	}
	hard := 0
	for _, d := range diags {
		if d.Level == "error" {
			hard++
			fmt.Fprintln(diagOut, "  ERROR "+d.Msg)
		} else {
			fmt.Fprintln(diagOut, "  info  "+d.Msg)
		}
	}
	if hard > 0 {
		fmt.Fprintf(diagOut, "RESOLVE FAILED — %d error(s)\n", hard)
		return 1
	}
	migrated, err := render(repo, cat, order, st, stderr)
	if err != nil {
		return stopped(err, stderr)
	}
	fmt.Fprintf(stdout, "rendered .generated/compose.yml — %d app(s) from apps/ + platform-base/\n", len(migrated))
	files, err := composeFiles(repo)
	if err != nil {
		return stopped(err, stderr)
	}
	fmt.Fprintln(stdout, "  compose files: -f "+strings.Join(files, " -f "))
	return 0
}

// stopped answers an error the way reconcile.py stops: a SystemExit's message as it is, anything
// else one FATAL line; exit 1 either way.
func stopped(err error, stderr io.Writer) int {
	var x *exit
	if errors.As(err, &x) {
		fmt.Fprintln(stderr, x.msg)
		return 1
	}
	return failed(err, stderr)
}

// render is render(cat, order, state): every file, in reconcile.py's order; the apps whose compose
// file is included.
func render(repo string, cat *Catalog, order []string, st *State, stderr io.Writer) ([]string, error) {
	gen := filepath.Join(repo, genDir)
	if err := mkdir(gen); err != nil {
		return nil, err
	}
	// FIRST: compose reads .env right after this, and every host below interpolates its slug
	if err := syncIdentity(repo, stderr); err != nil {
		return nil, err
	}
	env, err := readDotenv(repo)
	if err != nil {
		return nil, err
	}
	if err := archiveGeneration(gen); err != nil {
		return nil, err
	}
	var includes, migrated []string
	for _, aid := range order {
		app := cat.Apps[aid]
		doc := app.doc
		comp := get(doc, "compose")
		if !truthy(comp) {
			continue
		}
		rel, err := checkoutPath(repo, app.Dir, comp, aid+": compose")
		if err != nil {
			return nil, err
		}
		includes, migrated = append(includes, rel), append(migrated, aid)
	}
	lines := []string{
		"# GENERATED by platform/manager/reconcile.py — DO NOT EDIT.",
		"# Source of truth: apps/*/app.json + platform.state.yaml",
		fmt.Sprintf("# migrated apps (%d): %s", len(migrated), either(strings.Join(migrated, ", "), "(none yet)")),
		"",
		"include:",
		"# shared external network (root compose.yml) — required by every service",
		"- compose.yml",
	}
	for _, inc := range includes {
		lines = append(lines, "- "+inc)
	}
	if err := write(filepath.Join(gen, "compose.yml"), strings.Join(lines, "\n")+"\n"); err != nil {
		return nil, err
	}
	// The overlays: written when they say something, removed when they no longer do — a stale one would
	// keep a route, or a cutover wrapping a command that no longer exists.
	routing, err := renderRouting(repo, cat, order, env)
	if err != nil {
		return nil, err
	}
	if err := writeOrRemove(filepath.Join(gen, "routing.override.yml"), routing); err != nil {
		return nil, err
	}
	broker, err := renderBroker(cat, order)
	if err != nil {
		return nil, err
	}
	if err := writeOrRemove(filepath.Join(gen, "connections.override.yml"), broker); err != nil {
		return nil, err
	}
	if err := renderGlitchtip(gen, cat, order); err != nil {
		return nil, err
	}
	served, refusals, err := servedOf(repo, st)
	if err != nil {
		return nil, err
	}
	if len(refusals) > 0 {
		return nil, &exit{"SERVE PLAN REFUSED:\n  - " + strings.Join(refusals, "\n  - ")}
	}
	framed, err := framedHosts(cat, order, env)
	if err != nil {
		return nil, err
	}
	if err := renderServe(repo, gen, cat, served, framed, env, order); err != nil {
		return nil, err
	}
	if err := renderRegistries(repo, gen, cat, order, served, framed, env); err != nil {
		return nil, err
	}
	if err := renderAgentContext(gen, cat, order); err != nil {
		return nil, err
	}
	if err := renderAuthentik(repo, cat, order, served, env); err != nil {
		return nil, err
	}
	instances := getOr(st.Doc, "instances", yamlish.NewMap())
	if err := write(filepath.Join(gen, "resolved.json"), yamlish.IndentJSON(ordered(
		"order", strs(order...), "migrated", strs(migrated...), "instances", instances))); err != nil {
		return nil, err
	}
	return migrated, nil
}

// renderServe is render_serve(): the reverse plane's traefik file (into traefik's own config
// directory: its file provider is the one place an external server URL is accepted) and the link
// proxy's network aliases — written, or removed, on every render, so an office un-declared loses its
// routes in the same breath as its tiles. `framed` rides along: this office's own framed hosts take
// the same two routers a remote app of its own host does.
func renderServe(repo, gen string, cat *Catalog, served []remoteEntry, framed map[string]string, env *dotenv, order []string) error {
	dest := filepath.Join(repo, "platform-base", "traefik", "config", "zz-serve.yaml")
	aliases := filepath.Join(gen, "remote.override.yml")
	routers := map[string]string{}
	for aid, host := range framed {
		routers[aid+"-frame"] = host
	}
	lanDomain, lanPort := env.lanName(order)
	doc, err := serveRender(served, cat, env.domain(), env.consolePort(), routers, lanDomain, lanPort)
	if err != nil {
		return err
	}
	if doc == "" {
		if err := unlink(dest); err != nil {
			return err
		}
		return unlink(aliases)
	}
	if err := writeText(dest, doc); err != nil {
		return err
	}
	overlay, err := renderAliases(served)
	if err != nil {
		return err
	}
	if overlay == "" {
		return unlink(aliases)
	}
	return writeText(aliases, overlay)
}

// renderGlitchtip is render_glitchtip(): the GlitchTip projects, one per enabled app that declares
// `observability`, sorted by name — derived, so a base app never names its consumers.
func renderGlitchtip(gen string, cat *Catalog, order []string) error {
	type project struct{ name, platform string }
	var projects []project
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		o := get(doc, "observability")
		if !truthy(o) {
			continue
		}
		om, err := asDict(o, aid+": observability")
		if err != nil {
			return err
		}
		platform, err := index(om, "sentry_platform", aid+": observability")
		if err != nil {
			return err
		}
		projects = append(projects, project{pyval.Str(getOr(om, "sentry_project", aid)), pyval.Str(platform)})
	}
	sort.SliceStable(projects, func(i, j int) bool { return projects[i].name < projects[j].name })
	var b strings.Builder
	b.WriteString("# GENERATED by platform/manager/reconcile.py from each app's observability{} — DO NOT EDIT.\n" +
		"# Source of truth: apps/*/app.json + platform-base/*/app.json\nprojects:\n")
	for _, p := range projects {
		fmt.Fprintf(&b, "  - { name: %s platform: %s }\n", pyLjust(p.name+",", 20), p.platform)
	}
	return write(filepath.Join(gen, "glitchtip.projects.yml"), b.String())
}

const brokerHeader = "# GENERATED by platform/manager/reconcile.py — DO NOT EDIT.\n" +
	"# Credential-broker cutovers, compiled from each app.json's `broker` block. Each app\n" +
	"# below runs with its secrets BLANK in the environment; they are leased at boot from\n" +
	"# connections, which identifies the container over the docker socket and grants only\n" +
	"# what that app's own connections[] declares. Every grant is logged\n" +
	"# (GET /api/broker/audit). Apps without a `broker` block are untouched.\n" +
	"#\n" +
	"# Host paths are repo-root-relative: every consumer invokes compose with\n" +
	"# --project-directory <repo> (scripts/dc / dcx), so relative binds resolve there.\n"

// renderBroker is render_broker(cat, order): for each app in order that declares a `broker` block,
// its service wrapped in the connections injector — the secrets it names blank in the environment,
// connections healthy first, the injector mounted read-only — or "" when no app declares one (render
// then removes the file).
func renderBroker(cat *Catalog, order []string) (string, error) {
	svcs := yamlish.NewMap()
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		b := get(doc, "broker")
		if !truthy(b) {
			continue
		}
		bm, err := asDict(b, aid+": broker")
		if err != nil {
			return "", err
		}
		named := get(bm, "service") // the broker's own service, else the app's first route's (read only then)
		if !truthy(named) {
			if named, err = routedService(doc, aid, aid); err != nil {
				return "", err
			}
		}
		svc := pyval.Str(named)
		env := []any{pyval.Str(getOr(bm, "url_env", "CONN_URL")) + "=http://connections:8990", "CONN_SERVICE=" + svc}
		blank, err := list(get(bm, "blank_env"), aid+": broker.blank_env")
		if err != nil {
			return "", err
		}
		names := make([]string, len(blank))
		for i, k := range blank {
			if names[i], err = asText(k, aid+": broker.blank_env"); err != nil {
				return "", err
			}
		}
		sort.Strings(names)
		for _, k := range names {
			env = append(env, k+"=")
		}
		entrypoint, err := index(bm, "entrypoint", aid+": broker")
		if err != nil {
			return "", err
		}
		ep, err := each(entrypoint, aid+": broker.entrypoint") // `list(b["entrypoint"])`
		if err != nil {
			return "", err
		}
		svcs.Set(svc, ordered(
			"depends_on", ordered("connections", ordered("condition", "service_healthy")),
			"volumes", strs("./platform-base/connections/inject.sh:/inject.sh:ro"),
			"environment", env,
			"entrypoint", append([]any{}, ep...)))
	}
	if svcs.Len() == 0 {
		return "", nil
	}
	body, err := yamlish.Marshal(ordered("services", svcs), yamlish.Options{SortKeys: true})
	if err != nil {
		return "", err
	}
	return brokerHeader + string(body), nil
}

// ── generations: every render archives the one before it ──────────────────────────────────────────

const keepGenerations = 20

// archiveGeneration is archive_generation(): what .generated/ holds now (all but generations/) copied
// into the next generation, in the directory's own order — a directory as shutil.copytree, anything
// else as shutil.copy2, the first that fails ending the render, as its exception does — and only the
// newest twenty kept. An empty .generated/ archives nothing.
func archiveGeneration(gen string) error {
	entries, err := dirEntries(gen)
	if err != nil {
		return died("%s: %v", genDir, err)
	}
	var live []string
	for _, e := range entries {
		if e.Name() != "generations" {
			live = append(live, e.Name())
		}
	}
	if len(live) == 0 {
		return nil
	}
	gensDir := filepath.Join(gen, "generations")
	next := "1" // int(the newest's name) + 1, as many digits as that takes, %04d
	if gens := generationDirs(gensDir); len(gens) > 0 {
		n, _ := new(big.Int).SetString(gens[len(gens)-1], 10)
		next = n.Add(n, big.NewInt(1)).String()
	}
	dst := filepath.Join(gensDir, strings.Repeat("0", max(0, 4-len(next)))+next)
	if err := os.MkdirAll(dst, 0o777); err != nil {
		return died("%s: %v", dst, err)
	}
	for _, name := range live {
		if err := copyEntry(filepath.Join(gen, name), filepath.Join(dst, name)); err != nil {
			return died("archiving %s: %v", name, err)
		}
	}
	gens := generationDirs(gensDir)
	for _, old := range gens[:max(0, len(gens)-keepGenerations)] {
		// rmtree(ignore_errors=True): whatever cannot go stays — a generation that is a link, too. One
		// difference, on Windows only: a read-only file there rmtree leaves, and RemoveAll removes. A
		// walk that left it made Defender take dgo.exe for ransomware (Filecoder, a false positive).
		if fi, err := os.Lstat(filepath.Join(gensDir, old)); err == nil && fi.Mode()&os.ModeSymlink == 0 {
			os.RemoveAll(filepath.Join(gensDir, old))
		}
	}
	return nil
}

// copyEntry is `(shutil.copytree if src.is_dir() else shutil.copy2)(src, dst)`: is_dir() follows a link.
func copyEntry(src, dst string) error {
	if fi, err := os.Stat(src); err == nil && fi.IsDir() {
		return copytree(src, dst)
	}
	return copy2(src, dst)
}

// copytree is shutil.copytree(src, dst): the directory listed, then made; each entry copied as
// copyEntry copies it, one that fails noted and passed over — every other one is still copied, which
// is what an archive that fails holds; then the directory's own times and mode; then the failures, if
// any, as one error (shutil.Error).
func copytree(src, dst string) error {
	entries, err := dirEntries(src)
	if err != nil {
		return err
	}
	if err := os.Mkdir(dst, 0o777); err != nil {
		return err
	}
	var failed []string
	for _, e := range entries {
		if err := copyEntry(filepath.Join(src, e.Name()), filepath.Join(dst, e.Name())); err != nil {
			failed = append(failed, err.Error())
		}
	}
	// a directory's times may fail to copy on Windows, which copytree lets pass
	if err := copystat(src, dst); err != nil && runtime.GOOS != "windows" {
		failed = append(failed, err.Error())
	}
	if len(failed) > 0 {
		return errors.New(strings.Join(failed, "; "))
	}
	return nil
}

// copy2 is shutil.copy2(src, dst): the bytes (a link followed), then copystat — and, as copyfile
// refuses it, never a named pipe, whose read would wait for a writer.
func copy2(src, dst string) error {
	if fi, err := os.Stat(src); err == nil && fi.Mode()&fs.ModeNamedPipe != 0 {
		return fmt.Errorf("`%s` is a named pipe", src)
	}
	data, err := os.ReadFile(src)
	if err != nil {
		return err
	}
	if err := os.WriteFile(dst, data, 0o666); err != nil {
		return err
	}
	return copystat(src, dst)
}

// copystat is shutil.copystat(src, dst): the source's times — its modification time here, which is
// what a later look compares — then its mode bits, S_IMODE's twelve (setgid on a directory included),
// in that order: a read-only copy still takes its times.
func copystat(src, dst string) error {
	fi, err := os.Stat(src)
	if err != nil {
		return err
	}
	if err := os.Chtimes(dst, fi.ModTime(), fi.ModTime()); err != nil {
		return err
	}
	return os.Chmod(dst, fi.Mode()&(fs.ModePerm|fs.ModeSetuid|fs.ModeSetgid|fs.ModeSticky))
}

// dirEntries is os.listdir / os.scandir: a directory's entries in the directory's own order — the order
// Python acts in, which decides what is left where it stops half way — or the error, and then none.
func dirEntries(dir string) ([]os.DirEntry, error) {
	f, err := os.Open(dir)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	entries, err := f.ReadDir(-1)
	if err != nil {
		return nil, err
	}
	return entries, nil
}

// ── writing, as reconcile.py writes ────────────────────────────────────────────────────────────────

// write is write(path, text): the text's bytes, as they are on every OS — and nothing at all when the
// file already holds them, because a watcher cannot tell a rewrite from a change.
func write(path, text string) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, []byte(text)) {
		return nil
	}
	return writeText(path, text)
}

// writeText is reconcile.py's _put: the bytes, every time — and a compiled file another user wrote, in
// a directory this one owns, is replaced rather than refused (a control plane compiling as root inside
// its container; the Dell, 2026-11-01, DGO-1080). Only on that failure: a rename on every write would
// leave a single-file mount on the old inode.
func writeText(path, text string) error {
	err := os.WriteFile(path, []byte(text), 0o666)
	if err != nil && denied(err) {
		if os.Remove(path) == nil {
			err = os.WriteFile(path, []byte(text), 0o666)
		}
	}
	if err != nil {
		return died("%v", err)
	}
	return nil
}

// writeOrRemove writes an overlay that says something and removes one that no longer does
// (`elif path.exists(): path.unlink()`).
func writeOrRemove(path, text string) error {
	if text != "" {
		return write(path, text)
	}
	if !exists(path) { // exists() follows a link: a dangling one is left where it is
		return nil
	}
	return unlink(path)
}

// unlink is Path.unlink(missing_ok=True): a file — or a link, dangling or not — removed; nothing there
// is nothing to do; a directory is where unlink raises (os.Remove would take an empty one). Only
// FileNotFoundError is "nothing there": a path through a file (ENOTDIR on Linux; Windows says the
// path is not found) or one this user may not search raises, as os.unlink does.
func unlink(path string) error {
	fi, err := os.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return died("%v", err)
	}
	if fi.IsDir() {
		return died("%s: IsADirectoryError: it is a directory", path)
	}
	if err := os.Remove(path); err != nil {
		return died("%v", err)
	}
	return nil
}

// mkdir is Path.mkdir(exist_ok=True) — parents included, as every directory it is asked for here has
// its parent already.
func mkdir(dir string) error {
	if err := os.MkdirAll(dir, 0o777); err != nil {
		return died("%v", err)
	}
	return nil
}

// checkoutPath is `(a["_dir"] / rel).relative_to(REPO).as_posix()`: a path the manifest names, joined
// to its directory and written relative to the checkout with forward slashes — lexically, as pathlib
// does (no link followed, "." dropped, ".." kept); outside the checkout, where Python raises.
func checkoutPath(repo, dir string, rel any, where string) (string, error) {
	name, err := asText(rel, where)
	if err != nil {
		return "", err
	}
	full, root := pathParts(joinPath(dir, name)), pathParts(repo)
	if len(full) < len(root) {
		return "", died("%s: ValueError: %s is not in the subpath of %s", where, pyval.Repr(name), pyval.Repr(repo))
	}
	for i := range root {
		if !samePart(full[i], root[i]) {
			return "", died("%s: ValueError: %s is not in the subpath of %s", where, pyval.Repr(name), pyval.Repr(repo))
		}
	}
	return strings.Join(full[len(root):], "/"), nil
}

// pathParts are a path's parts as pathlib holds them: split at every separator (either slash on
// Windows), the empty and "." parts dropped, the drive or root kept as the first part.
func pathParts(p string) []string {
	vol := filepath.VolumeName(p)
	rest := p[len(vol):]
	var parts []string
	if vol != "" || strings.HasPrefix(rest, "/") || strings.HasPrefix(rest, string(filepath.Separator)) {
		parts = append(parts, vol+"/")
	}
	for _, part := range strings.FieldsFunc(rest, func(r rune) bool { return r == '/' || r == filepath.Separator }) {
		if part != "." {
			parts = append(parts, part)
		}
	}
	return parts
}

// samePart compares two parts as PurePath does: by case on Windows' paths, exactly elsewhere.
func samePart(a, b string) bool {
	if runtime.GOOS == "windows" {
		return strings.EqualFold(a, b)
	}
	return a == b
}
