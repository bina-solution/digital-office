// ── routing.override.yml: the edge's labels and what an app contributes to a base app ─────────────

const routingHeader = "# GENERATED by platform/manager/reconcile.py — DO NOT EDIT.\n" +
	"# Traefik + homepage labels from each app.json `routing`, plus the env each app\n" +
	"# declares in `contributes.env` for a base app (the layering rule forbids the base\n" +
	"# app from naming its layer-3 consumers).\n"

var notEnvName = regexp.MustCompile(`[^A-Z0-9]`)

// overlay is the services mapping an overlay is built in: services.<svc>.<key> is a list that items
// are appended to — created, empty, the first time it is asked for (setdefault), as Python's is.
type overlay struct{ svcs *yamlish.Map }

func (o overlay) add(svc any, key string, items ...any) {
	name := pyval.Str(svc)
	sv, ok := o.svcs.Get(name)
	if !ok {
		sv = yamlish.NewMap()
		o.svcs.Set(name, sv)
	}
	m := sv.(*yamlish.Map)
	cur, _ := m.Get(key)
	have, _ := cur.([]any)
	m.Set(key, append(append([]any{}, have...), items...))
}

// renderRouting is render_routing(cat, order): every enabled app's traefik labels (its console
// passthroughs first), the env and volumes an app contributes to an enabled base app, the host
// variables the committed sign-in blueprint resolves (on the services that apply it), the declared
// engine profiles, and the console's map of platform services — "" when there is nothing to say.
func renderRouting(repo string, cat *Catalog, order []string, env *dotenv) (string, error) {
	o := overlay{yamlish.NewMap()}
	console, consoleR := (*yamlish.Map)(nil), (*yamlish.Map)(nil)
	if app := cat.Apps["console"]; app != nil {
		console = app.doc
		routes, err := list(get(console, "routing"), "console: routing")
		if err != nil {
			return "", err
		}
		if len(routes) > 0 {
			if consoleR, err = asDict(routes[0], "console: routing[0]"); err != nil {
				return "", err
			}
		}
	}
	enabled := map[string]bool{}
	for _, aid := range order {
		enabled[aid] = true
	}
	waker, err := onDemandWaker(cat, enabled)
	if err != nil {
		return "", err
	}
	woken := false
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		items, err := each(getOr(doc, "routing", []any{}), aid+": routing") // `a.get("routing", [])`: no `or`
		if err != nil {
			return "", err
		}
		routes, err := asDicts(items, aid+": routing")
		if err != nil {
			return "", err
		}
		for _, r := range routes {
			module, err := dict(get(r, "module"), aid+": routing.module")
			if err != nil {
				return "", err
			}
			if pass, err := list(get(module, "passthrough"), aid+": module.passthrough"); err != nil {
				return "", err
			} else if len(pass) > 0 {
				if consoleR == nil || consoleR.Len() == 0 { // `not console_r`: no route, or an empty one
					return "", &exit{aid + ": module.passthrough requires the console app"}
				}
				labels, err := passthroughLabels(aid, r, consoleR, console, env)
				if err != nil {
					return "", err
				}
				o.add(either(get(r, "service"), aid), "labels", labels...)
			}
			if !truthy(getOr(r, "emit_labels", true)) {
				continue // the app carries its own labels in its own compose
			}
			framed := ""
			if host := get(r, "host"); truthy(get(module, "external")) && truthy(host) && env.domain() == "localhost" &&
				pyEqual(getOr(r, "auth", "sso"), "sso") {
				if framed, err = consoleFramedHost(cat, host, env); err != nil {
					return "", err
				}
			}
			labels, err := routingLabels(aid, r, framed, env)
			if err != nil {
				return "", err
			}
			o.add(either(get(r, "service"), aid), "labels", labels...)
			// on demand (DGO-1270): the idle window on the app, its routers again on the waker
			if truthy(get(r, "on_demand")) {
				idle, err := onDemandIdle(aid, r)
				if err != nil {
					return "", err
				}
				if waker != nil {
					o.add(either(get(r, "service"), aid), "labels", onDemandLabel+"="+strconv.FormatInt(idle, 10),
						onDemandAppLabel+"="+aid)
					o.add(waker.svc, "labels", onDemandLabels(aid, r, labels)...)
					woken = true
				}
			}
		}
	}
	if woken {
		o.add(waker.svc, "labels", "traefik.http.services."+wakeService+".loadbalancer.server.port="+waker.port)
	}

	// A contribution lands only on an app that is IN the compiled set: an overlay naming a service no
	// compose file defines makes the whole project invalid.
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		contrib, err := dict(get(doc, "contributes"), aid+": contributes")
		if err != nil {
			return "", err
		}
		envs, err := dict(get(contrib, "env"), aid+": contributes.env")
		if err != nil {
			return "", err
		}
		for _, base := range envs.Keys() {
			if _, known := cat.Apps[base]; !known || !enabled[base] {
				continue
			}
			bdoc := cat.Apps[base].doc
			tgt, err := routedService(bdoc, base, base)
			if err != nil {
				return "", err
			}
			vars, err := asDict(get(envs, base), aid+": contributes.env."+base)
			if err != nil {
				return "", err
			}
			var lines []any
			keys := vars.Keys() // sorted(env.items()): the keys are distinct, so by key
			sort.Strings(keys)
			for _, k := range keys {
				lines = append(lines, k+"="+pyval.Str(get(vars, k)))
			}
			o.add(tgt, "environment", lines...)
		}
		vols, err := dict(get(contrib, "volumes"), aid+": contributes.volumes")
		if err != nil {
			return "", err
		}
		for _, base := range vols.Keys() {
			// "<app>" lands on that app's routing service, "<app>:<service>" on one named service of it
			baseID, svcName, _ := strings.Cut(base, ":")
			if _, known := cat.Apps[baseID]; !known || !enabled[baseID] {
				continue
			}
			var tgt any = svcName
			if svcName == "" {
				bdoc := cat.Apps[baseID].doc
				if tgt, err = routedService(bdoc, baseID, baseID); err != nil {
					return "", err
				}
			}
			items, err := each(get(vols, base), aid+": contributes.volumes."+base) // `.extend(vols)`
			if err != nil {
				return "", err
			}
			o.add(tgt, "volumes", items...)
		}
	}

	// The hosts the COMMITTED sign-in blueprint resolves (`!Env [NAME_BASE_URL, default]`), compiled
	// onto the services that apply blueprints — those that mount them — and only while authentik is on.
	if enabled["authentik"] && cat.Apps["authentik"] != nil {
		committed, _, err := committedSSOEstate(repo)
		if err != nil {
			return "", err
		}
		hostEnv, err := ssoHostEnv(repo, cat, order)
		if err != nil {
			return "", err
		}
		var lines []any
		for _, k := range sortedKeys(hostEnv) {
			if _, owned := committed[k]; owned {
				lines = append(lines, k+"=${"+k+":-"+hostEnv[k]+"}")
			}
		}
		appliers, err := composeServicesMounting(repo, cat.Apps["authentik"], "/blueprints/custom")
		if err != nil {
			return "", err
		}
		for _, svc := range appliers {
			if len(lines) > 0 {
				o.add(svc, "environment", lines...)
			}
		}
	}

	// The catalogue plane: an app's declared engine profiles, handed to it as JSON on its own variable.
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		eng, err := dict(get(doc, "engine"), aid+": engine")
		if err != nil {
			return "", err
		}
		profs := get(eng, "profiles")
		if !truthy(profs) {
			continue
		}
		tgt, err := routedService(doc, aid, aid)
		if err != nil {
			return "", err
		}
		name := notEnvName.ReplaceAllString(pyUpper(aid), "_") + "_ENGINE_PROFILES"
		o.add(tgt, "environment", name+"="+yamlish.CanonicalJSON(profs))
	}

	// The connection plane: every capability that declares the platform-service contract, by name.
	plat := yamlish.NewMap()
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		caps, err := dicts(get(doc, "capabilities"), aid+": capabilities")
		if err != nil {
			return "", err
		}
		for _, c := range caps {
			if pyEqual(get(c, "contract"), "platform-service.v1") && truthy(get(c, "endpoint")) {
				name, err := index(c, "name", aid+": capabilities")
				if err != nil {
					return "", err
				}
				endpoint, _ := index(c, "endpoint", aid+": capabilities")
				plat.Set(pyval.Str(name), endpoint)
			}
		}
	}
	if plat.Len() > 0 && console != nil {
		tgt, err := routedService(console, "console", "console")
		if err != nil {
			return "", err
		}
		o.add(tgt, "environment", "PLATFORM_SERVICES="+yamlish.FlaskJSON(plat))
	}

	if o.svcs.Len() == 0 {
		return "", nil
	}
	body, err := yamlish.Marshal(ordered("services", o.svcs), yamlish.Options{SortKeys: true})
	if err != nil {
		return "", err
	}
	return routingHeader + string(body), nil
}

// routingLabels is routing_labels(app_id, r, framed): the platform's three routers per host — the
// `.localhost` one, and the app's own host on web and on websecure with TLS — every one behind the
// sign-in middleware when the route is `auth: sso`, a fourth for the host the shell frames the app on
// where its own variable does not already route it, and the service's port.
func routingLabels(appID string, r *yamlish.Map, framed string, env *dotenv) ([]any, error) {
	svc := pyval.Str(either(get(r, "service"), appID))
	name := pyval.Str(either(get(r, "name"), appID))
	hostv, err := index(r, "host", appID+": routing")
	if err != nil {
		return nil, err
	}
	port, err := index(r, "port", appID+": routing")
	if err != nil {
		return nil, err
	}
	host, err := asText(hostv, appID+": routing.host")
	if err != nil {
		return nil, err
	}
	hostEnv := env.traefikHost(pyval.Str(either(get(r, "url_env"), baseURLEnv(appID))), host+".${DEPLOYMENT_DOMAIN:-localhost}")
	auth := getOr(r, "auth", "sso")
	sso := pyEqual(auth, "sso")
	// `basic` was once in the schema and no middleware implements it: a route the emitter cannot
	// protect is refused here, never published open
	if !sso && !pyEqual(auth, "none") {
		return nil, &exit{appID + ": routing auth '" + pyval.Str(auth) + "' is declared in the schema but not implemented by the " +
			"label emitter — it would publish an UNAUTHENTICATED route. Use 'sso' or 'none'."}
	}
	labels := []any{"traefik.enable=true"}
	router := func(suffix, rule, entry string, tls bool) {
		p := "traefik.http.routers." + name + "-" + suffix
		labels = append(labels, p+".rule="+rule, p+".entrypoints="+entry)
		if tls {
			// the office names its issuer (DGO-901): empty on an office with no public name, so its edge
			// never asks Let's Encrypt for a .localhost certificate — reconcile.py writes the same text
			labels = append(labels, p+".tls=true", p+".tls.certresolver=${TRAEFIK_CERTRESOLVER-myresolver}")
		}
		labels = append(labels, p+".service="+svc)
		if sso { // authentik@file: the file provider's middleware, which exists whatever the docker snapshot holds
			labels = append(labels, p+".middlewares=authentik@file")
		}
	}
	router("local", "Host(`"+host+".localhost`)", "web", false)
	router("http", "Host(`"+hostEnv+"`)", "web", false)
	router("https", "Host(`"+hostEnv+"`)", "websecure", true)
	if framed != "" && !ownRouteHosts(appID, r, env)[framed] {
		router("frame", "Host(`"+framed+"`)", "web", false)
	}
	return append(labels, "traefik.http.services."+svc+".loadbalancer.server.port="+pyval.Str(port)), nil
}

// ── on demand (DGO-1270): reconcile.py's ON_DEMAND_LABEL, on_demand_waker, on_demand_idle, on_demand_labels ──
// A route declaring `on_demand: {idle: 2h}` carries its idle window as a label autoheal reads, and the
// waker (app-management) carries the route's routers again at priority 1, behind the same sign-in and a
// header naming the app, so a stopped app's address still answers and opening it starts it.

const (
	onDemandLabel    = "binaos.on-demand.idle"
	onDemandAppLabel = "binaos.on-demand.app"
	wakeService      = "dgo-wake"
	wakeHeader       = "X-Dgo-Wake"
)

var idleRe = regexp.MustCompile(`^([1-9][0-9]*)([smh])$`)

type wakerRoute struct{ svc, port string }

// onDemandWaker is on_demand_waker(): app-management's first route, nil when the office does not run it.
func onDemandWaker(cat *Catalog, enabled map[string]bool) (*wakerRoute, error) {
	app := cat.Apps["app-management"]
	if !enabled["app-management"] || app == nil {
		return nil, nil
	}
	routes, err := list(get(app.doc, "routing"), "app-management: routing")
	if err != nil || len(routes) == 0 {
		return nil, err
	}
	r, err := asDict(routes[0], "app-management: routing[0]")
	if err != nil {
		return nil, err
	}
	port, err := index(r, "port", "app-management: routing")
	if err != nil {
		return nil, err
	}
	return &wakerRoute{svc: pyval.Str(either(get(r, "service"), "app-management")), port: pyval.Str(port)}, nil
}

// onDemandIdle is on_demand_idle(): the window in seconds, 5 minutes to 30 days, or the refusal.
func onDemandIdle(appID string, r *yamlish.Map) (int64, error) {
	od, err := dict(get(r, "on_demand"), appID+": routing.on_demand")
	if err != nil {
		return 0, err
	}
	raw := pyval.Str(either(get(od, "idle"), ""))
	var secs int64
	if m := idleRe.FindStringSubmatch(raw); m != nil && len(raw) <= 10 {
		n, _ := strconv.ParseInt(m[1], 10, 64)
		secs = n * map[string]int64{"s": 1, "m": 60, "h": 3600}[m[2]]
	}
	if secs < 300 || secs > 30*86400 {
		return 0, &exit{appID + ": routing.on_demand.idle must be a duration from 5 minutes to 30 days " +
			"(\"30m\", \"2h\"), got " + pyval.Repr(raw)}
	}
	return secs, nil
}

// onDemandLabels is on_demand_labels(): every router `labels` declares for the route, again under
// `<name>-wake-<suffix>` — the waker's service, priority 1, the route's middlewares and then the one
// that names the app.
func onDemandLabels(appID string, r *yamlish.Map, labels []any) []any {
	name := pyval.Str(either(get(r, "name"), appID))
	pre := "traefik.http.routers." + name + "-"
	type field struct{ name, value string }
	var suffixes []string
	routers := map[string][]field{}
	for _, l := range labels {
		key, value, _ := strings.Cut(pyval.Str(l), "=")
		if !strings.HasPrefix(key, pre) {
			continue
		}
		suffix, f, _ := strings.Cut(key[len(pre):], ".")
		if _, seen := routers[suffix]; !seen {
			suffixes = append(suffixes, suffix)
		}
		routers[suffix] = append(routers[suffix], field{f, value})
	}
	var out []any
	for _, suffix := range suffixes {
		p := "traefik.http.routers." + name + "-wake-" + suffix
		var chain []string
		for _, f := range routers[suffix] {
			if f.name == "middlewares" {
				chain = append(chain, f.value)
				continue
			}
			value := f.value
			if f.name == "service" {
				value = wakeService
			}
			out = append(out, p+"."+f.name+"="+value)
		}
		out = append(out, p+".priority=1", p+".middlewares="+strings.Join(append(chain, name+"-wake"), ","))
	}
	return append(out, "traefik.http.middlewares."+name+"-wake.headers.customrequestheaders."+wakeHeader+"="+appID)
}

// ownRouteHosts is _own_route_hosts: the hosts a routing entry's own routers already match here.
func ownRouteHosts(appID string, r *yamlish.Map, env *dotenv) map[string]bool {
	val := pyval.Strip(env.value(pyval.Str(either(get(r, "url_env"), baseURLEnv(appID)))))
	hosts := map[string]bool{pyval.Str(either(get(r, "host"), appID)) + ".localhost": true}
	if val != "" {
		if _, after, ok := strings.Cut(val, "//"); ok {
			val = after
		}
		val, _, _ = strings.Cut(val, "/")
		val, _, _ = strings.Cut(val, ":")
		hosts[val] = true
	}
	return hosts
}

// passthroughLabels is console_passthrough_labels(): direct edge routes for the transports the
// console's proxy cannot carry (a websocket), on the console's own hosts — under the app's /a/<alias>
// mount with the prefix stripped, or at the console's root for a `mount: root` path, carved out of the
// paths the console reserves — always behind the sign-in middleware.
func passthroughLabels(appID string, r, consoleR, console *yamlish.Map, env *dotenv) ([]any, error) {
	module, _ := dict(get(r, "module"), appID+": routing.module")
	specs, _ := list(get(module, "passthrough"), appID+": module.passthrough")
	if !truthy(getOr(module, "embed", true)) {
		return nil, &exit{appID + ": module.passthrough requires module.embed=true"}
	}
	if !pyEqual(getOr(r, "auth", "sso"), "sso") {
		return nil, &exit{appID + ": console passthrough must inherit auth:sso"}
	}
	alias := get(module, "alias")
	if !truthy(alias) {
		return nil, &exit{appID + ": module.passthrough requires module.alias"}
	}
	svc := pyval.Str(either(get(r, "service"), appID))
	port, err := index(r, "port", appID+": routing")
	if err != nil {
		return nil, err
	}
	chv, err := index(consoleR, "host", "console: routing")
	if err != nil {
		return nil, err
	}
	cHost, err := asText(chv, "console: routing.host")
	if err != nil {
		return nil, err
	}
	consoleEnv := env.traefikHost(baseURLEnv("console"), cHost+".${DEPLOYMENT_DOMAIN:-localhost}")
	labels := []any{"traefik.enable=true"}
	reservedRule := ""
	reserved, err := list(get(console, "reserved_paths"), "console: reserved_paths")
	if err != nil {
		return nil, err
	}
	var alts []string
	for _, rp := range reserved {
		if s := pyval.Str(rp); s != "/a" {
			alts = append(alts, pyReEscape(strings.TrimLeft(s, "/")))
		}
	}
	if len(alts) > 0 {
		reservedRule = " && !PathRegexp(`^/(" + strings.Join(alts, "|") + ")(/|$)`)"
	}
	for i, sv := range specs {
		spec, err := asDict(sv, appID+": module.passthrough")
		if err != nil {
			return nil, err
		}
		transport, err := index(spec, "transport", appID+": module.passthrough")
		if err != nil {
			return nil, err
		}
		route := appID + "-console-" + pyval.Str(transport) + "-" + itoa(i)
		root := pyEqual(getOr(spec, "mount", "alias"), "root")
		path, err := index(spec, "path", appID+": module.passthrough")
		if err != nil {
			return nil, err
		}
		mount := pyval.Str(path)
		if !root {
			mount = "/a/" + pyval.Str(alias) + mount
		}
		matcher := "Path"
		if pyEqual(getOr(spec, "match", "exact"), "prefix") {
			matcher = "PathPrefix"
		}
		rule := matcher + "(`" + mount + "`)"
		if root {
			rule += reservedRule
		}
		var middlewares []string
		if !root && truthy(getOr(spec, "strip_mount_prefix", true)) {
			strip := route + "-strip"
			labels = append(labels, "traefik.http.middlewares."+strip+".stripprefix.prefixes=/a/"+pyval.Str(alias))
			middlewares = append(middlewares, strip)
		}
		middlewares = append(middlewares, "authentik@file")
		for _, rt := range []struct {
			suffix, host, entry string
			tls                 bool
		}{{"local", cHost + ".localhost", "web", false}, {"http", consoleEnv, "web", false}, {"https", consoleEnv, "websecure", true}} {
			key := "traefik.http.routers." + route + "-" + rt.suffix
			labels = append(labels, key+".rule=Host(`"+rt.host+"`) && "+rule, key+".entrypoints="+rt.entry, key+".priority=100")
			if rt.tls {
				labels = append(labels, key+".tls=true", key+".tls.certresolver=${TRAEFIK_CERTRESOLVER-myresolver}")
			}
			labels = append(labels, key+".service="+svc, key+".middlewares="+strings.Join(middlewares, ","))
		}
	}
	return append(labels, "traefik.http.services."+svc+".loadbalancer.server.port="+pyval.Str(port)), nil
}

// pyReEscape is re.escape(): a backslash before each character a pattern gives a meaning to —
// ()[]{}?*+-|^$\.&~# and whitespace — as Python 3.7+ escapes them.
func pyReEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		if strings.ContainsRune("()[]{}?*+-|^$\\.&~# \t\n\r\v\f", r) {
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	return b.String()
}

// ── the hosts the shell frames an app on ──────────────────────────────────────────────────────────

// consoleFramedHost is console_framed_host(): `<host>.<console host>` — the address the shell derives
// for an app it frames on its own host, nested under the console so the two share a site on .localhost.
func consoleFramedHost(cat *Catalog, host any, env *dotenv) (string, error) {
	cHost, _, err := consoleHost(cat)
	if err != nil {
		return "", err
	}
	origin := env.value("CONSOLE_BASE_URL")
	if _, after, ok := strings.Cut(origin, "//"); ok {
		origin = after
	}
	origin, _, _ = strings.Cut(origin, "/")
	if origin == "" {
		origin = cHost + "." + either(env.value("DEPLOYMENT_DOMAIN"), "localhost").(string)
	}
	origin, _, _ = strings.Cut(origin, ":")
	return pyval.Str(host) + "." + origin, nil
}

// framedEntry is one of framed_sso_entries(): an app framed on a nested host, and the provider that
// host needs (a name of its own: a provider's name is its identity to authentik).
type framedEntry struct {
	aid, host string
	sso       *yamlish.Map // slug, display_name, host_expr
}

// framedSSOEntries is framed_sso_entries(): on a `.localhost` office only, the nested host of every
// enabled app the shell frames on its own host behind SSO — one provider for it, and one for the same
// host with the console's port where the app's own address is not already that host.
func framedSSOEntries(cat *Catalog, order []string, env *dotenv) ([]framedEntry, error) {
	if env.domain() != "localhost" {
		return nil, nil
	}
	port := env.consolePort()
	var out []framedEntry
	for _, aid := range order {
		doc := cat.Apps[aid].doc
		routes, err := dicts(get(doc, "routing"), aid+": routing")
		if err != nil {
			return nil, err
		}
		for _, r := range routes {
			m, err := dict(get(r, "module"), aid+": routing.module")
			if err != nil {
				return nil, err
			}
			if !truthy(get(m, "external")) || !truthy(get(r, "host")) || !pyEqual(getOr(r, "auth", "sso"), "sso") {
				continue
			}
			s, err := dict(get(r, "sso"), aid+": routing.sso")
			if err != nil {
				return nil, err
			}
			slug := pyval.Str(either(get(s, "slug"), aid))
			name := either(get(s, "display_name"), enName(get(doc, "title"), aid))
			host, err := index(r, "host", aid+": routing")
			if err != nil {
				return nil, err
			}
			framed, err := consoleFramedHost(cat, host, env)
			if err != nil {
				return nil, err
			}
			if port != "" {
				own := externalOrigin(aid, r, m, env, "")
				if _, after, ok := strings.Cut(own, "//"); ok {
					own = after
				}
				if own, _, _ = strings.Cut(own, ":"); own != framed {
					out = append(out, framedEntry{aid, framed, ordered("slug", slug+"-frame-port",
						"display_name", pyval.Str(name)+" Frame Port", "host_expr", frameHostExpr(framed+":"+port))})
				}
			}
			out = append(out, framedEntry{aid, framed, ordered("slug", slug+"-frame",
				"display_name", pyval.Str(name)+" Frame", "host_expr", frameHostExpr(framed))})
		}
	}
	return out, nil
}

// framedHosts is framed_hosts(): {app id: the host the shell frames it on}.
func framedHosts(cat *Catalog, order []string, env *dotenv) (map[string]string, error) {
	entries, err := framedSSOEntries(cat, order, env)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, e := range entries {
		out[e.aid] = e.host
	}
	return out, nil
}

// frameHostExpr is frame_host_expr(): a framed host's external_host — a literal host, its scheme
// following AUTH_PROTOCOL.
func frameHostExpr(host string) string {
	return `!Format ["%s://%s", !Env [AUTH_PROTOCOL, http], "` + host + `"]`
}

// externalOrigin is external_origin(): the browser origin of an app framed on its own host, read from
// the host variable it declares, else defaultHost (the host its routers fall back to) — "" where both
// are unset or a compose service name.
func externalOrigin(appID string, r, m *yamlish.Map, env *dotenv, defaultHost string) string {
	s, _ := get(r, "sso").(*yamlish.Map)
	name := either(either(get(s, "base_url_env"), get(m, "url_env")), baseURLEnv(appID))
	host := pyval.Strip(env.value(pyval.Str(name)))
	if host == "" {
		host = defaultHost
	}
	if _, after, ok := strings.Cut(host, "//"); ok {
		host = after
	}
	host, _, _ = strings.Cut(host, "/")
	bare, _, _ := strings.Cut(host, ":")
	if host == "" || !strings.Contains(bare, ".") {
		return ""
	}
	proto := env.value(strings.ReplaceAll(pyUpper(appID), "-", "_") + "_PROTOCOL")
	if proto != "http" && proto != "https" {
		proto = "https"
		if strings.HasSuffix(bare, "localhost") {
			proto = "http"
		}
	}
	return proto + "://" + host
}

// enName is en_name(): one name out of a `{he, en}` title or a plain string.
func enName(v any, fallback string) any {
	if m, ok := v.(*yamlish.Map); ok {
		return either(either(get(m, "en"), get(m, "he")), fallback)
	}
	return either(v, fallback)
}

func itoa(i int) string { return pyval.Str(int64(i)) }
